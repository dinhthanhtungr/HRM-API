using System;
using System.Collections.Generic;
using System.Linq;
using System.Runtime.CompilerServices;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace HRM.Diagnostics.Build;

[Generator]
public sealed class FeatureStepGenerator : IIncrementalGenerator
{
    private const string Timing = "global::HRM.Application.Commons.Diagnostics.RequestTiming";
    private static readonly SymbolDisplayFormat TypeFormat = SymbolDisplayFormat.FullyQualifiedFormat;
    private static readonly ConditionalWeakTable<MethodDeclarationSyntax, ManualTiming> ManualScopes = new();

    private sealed class ManualTiming(MethodDeclarationSyntax method)
    {
        internal bool HasSteps { get; } = method.DescendantNodes().OfType<IdentifierNameSyntax>()
            .Any(name => name.Identifier.ValueText == "RequestTiming");
    }

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var sites = context.SyntaxProvider.CreateSyntaxProvider(
            static (node, _) => node is InvocationExpressionSyntax { Expression: MemberAccessExpressionSyntax or SimpleNameSyntax } call &&
                (call.Parent is AwaitExpressionSyntax or EqualsValueClauseSyntax or ReturnStatementSyntax or
                    ArrowExpressionClauseSyntax or ExpressionStatementSyntax or MemberAccessExpressionSyntax or
                    ConditionalExpressionSyntax or AnonymousFunctionExpressionSyntax),
            static (ctx, ct) => BuildSite((InvocationExpressionSyntax)ctx.Node, ctx.SemanticModel, ct))
            .Where(static site => site != null);
        context.RegisterSourceOutput(sites.Collect(), static (output, items) =>
        {
            if (items.IsEmpty) return;
            var source = new StringBuilder("""
                // <auto-generated/>
                #nullable disable
                #pragma warning disable
                namespace System.Runtime.CompilerServices {
                    [global::System.AttributeUsage(global::System.AttributeTargets.Method, AllowMultiple = true)]
                    file sealed class InterceptsLocationAttribute(int version, string data) : global::System.Attribute {}
                }
                namespace HRM.Generated.Timing {
                    file static class FeatureSteps {

                """);
            var index = 0;
            foreach (var group in items.GroupBy(site => site!.Value.Body))
            {
                foreach (var site in group) source.AppendLine(site!.Value.Attribute);
                source.AppendLine(group.Key.Replace("__INTERCEPT__", "Run" + index++));
            }
            output.AddSource("FeatureSteps.g.cs", source.AppendLine("}}").ToString());
        });
    }

    private static (string Attribute, string Body)? BuildSite(InvocationExpressionSyntax call,
        SemanticModel model, System.Threading.CancellationToken ct)
    {
        var path = call.SyntaxTree.FilePath.Replace('\\', '/');
        if (!(path.Contains("/HRM.Application/Features/") || path.Contains("/HRM.Application/Commons/") ||
              path.Contains("/HRM.Api/Controllers/") || path.Contains("/HRM.Infrastructure/"))) return null;
        if (path.Contains("/obj/") || path.Contains("/Migrations/") || path.Contains("/Diagnostics/")) return null;
        // LINQ providers must receive their original expression trees. Ordinary delegates,
        // including async controller callbacks and transaction delegates, execute as code.
        foreach (var ancestor in call.Ancestors())
        {
            if (ancestor is QueryExpressionSyntax) return null;
            if (ancestor is AnonymousFunctionExpressionSyntax lambda &&
                model.GetTypeInfo(lambda, ct).ConvertedType?.TypeKind != TypeKind.Delegate) return null;
        }
        if (model.GetSymbolInfo(call, ct).Symbol is not IMethodSymbol called ||
            called.IsAbstract && called.IsStatic || called.ReturnsByRef || called.ReturnsByRefReadonly ||
            called.MethodKind is not (MethodKind.Ordinary or MethodKind.ReducedExtension)) return null;

        var target = called.ReducedFrom ?? called;
        if (target.IsConditional || target.IsPartialDefinition) return null;
        var owner = target.ContainingType;
        var task = called.ReturnType as INamedTypeSymbol;
        var asynchronous = task?.ContainingNamespace.ToDisplayString() == "System.Threading.Tasks" &&
            task.Name is "Task" or "ValueTask";
        var ownerNamespace = owner.ContainingNamespace.ToDisplayString();
        var awaited = call.Parent is AwaitExpressionSyntax ||
            call.Parent is MemberAccessExpressionSyntax { Name.Identifier.ValueText: "ConfigureAwait",
                Parent.Parent: AwaitExpressionSyntax };
        var businessCall = ownerNamespace.StartsWith("HRM.", StringComparison.Ordinal);
        // A forwarded Task can be observed without replacing it. A ValueTask may only be consumed once.
        if (asynchronous && !awaited && (!businessCall || task!.Name != "Task")) return null;
        var documentOutput = (ownerNamespace.StartsWith("QuestPDF.", StringComparison.Ordinal) && target.Name.StartsWith("Generate", StringComparison.Ordinal)) ||
            (ownerNamespace.StartsWith("ClosedXML.", StringComparison.Ordinal) && target.Name == "SaveAs");
        if (!asynchronous && ((!businessCall && !documentOutput) ||
            owner.Name == "OperationResult" ||
            call.Parent is MemberAccessExpressionSyntax ||
            called.ReturnType.AllInterfaces.Any(i => i.Name == "IQueryable") ||
            called.ReturnType.Name is "IQueryable" or "IOrderedQueryable")) return null;
        if (ownerNamespace.StartsWith("HRM.Application.Commons.Diagnostics", StringComparison.Ordinal) ||
            ownerNamespace == "MediatR" || owner.Name.Contains("Timing") || owner.IsValueType || owner.TypeKind == TypeKind.Delegate ||
            target.Parameters.Any(p => p.RefKind != RefKind.None) ||
            call.Expression is MemberAccessExpressionSyntax { Expression: BaseExpressionSyntax } ||
            !model.Compilation.IsSymbolAccessibleWithin(target, model.Compilation.Assembly)) return null;

        // Keep generic EF extensions generic, including queries over anonymous projections.
        var genericEf = target.IsExtensionMethod && ownerNamespace == "Microsoft.EntityFrameworkCore";
        if (genericEf) target = target.OriginalDefinition;
        else if (called.ReducedFrom != null && called.IsGenericMethod)
            target = target.ConstructedFrom.Construct(called.TypeArguments.ToArray());
        var typeParameters = genericEf ? target.TypeParameters : default;
        bool Visible(ITypeSymbol type) => type switch
        {
            ITypeParameterSymbol p => genericEf && typeParameters.Contains(p, SymbolEqualityComparer.Default),
            IArrayTypeSymbol a => Visible(a.ElementType),
            INamedTypeSymbol n => !n.IsAnonymousType && !n.IsFileLocal && !n.IsRefLikeType &&
                model.Compilation.IsSymbolAccessibleWithin(n.OriginalDefinition, model.Compilation.Assembly) &&
                n.TypeArguments.All(Visible) && (n.ContainingType == null || Visible(n.ContainingType)),
            _ => false
        };
        if (!Visible(target.ContainingType) || !Visible(target.ReturnType) ||
            !target.Parameters.All(p => Visible(p.Type)) || !target.TypeArguments.All(Visible)) return null;
        var method = call.FirstAncestorOrSelf<MethodDeclarationSyntax>();
        var enclosing = method?.FirstAncestorOrSelf<TypeDeclarationSyntax>();
        if (method == null || enclosing == null || ManualScopes.GetValue(method, m => new ManualTiming(m)).HasSteps) return null;
        var labelOwner = enclosing.Identifier.ValueText;
        if (method.Identifier.ValueText != "Handle") labelOwner += "_" + method.Identifier.ValueText;
        var resultName = call.Ancestors().TakeWhile(n => n is not StatementSyntax).OfType<VariableDeclaratorSyntax>()
            .FirstOrDefault()?.Identifier.ValueText;
        var label = "step_" + labelOwner + "_" + (resultName == null ? "" : resultName + "_") + target.Name;
        label = new string(label.Select(c => c <= 127 && char.IsLetterOrDigit(c) ? c : '_').ToArray());
#pragma warning disable RSEXPERIMENTAL002
        var location = model.GetInterceptableLocation(call, ct);
        if (location == null) return null;
        return (location.GetInterceptsLocationAttributeSyntax(),
            BuildInterceptor(target, called.ReducedFrom != null, genericEf, asynchronous, awaited, label));
#pragma warning restore RSEXPERIMENTAL002
    }

    private static string BuildInterceptor(IMethodSymbol target, bool reducedExtension, bool genericEf,
        bool asynchronous, bool awaited, string label)
    {
        var owner = target.ContainingType;
        var body = new StringBuilder("internal static ").Append(target.ReturnType.ToDisplayString(TypeFormat))
            .Append(" __INTERCEPT__");
        var args = target.IsGenericMethod
            ? "<" + string.Join(", ", target.TypeArguments.Select(t => t.ToDisplayString(TypeFormat))) + ">" : "";
        if (genericEf) body.Append(args);
        var parameters = target.Parameters.Select((p, i) => (i == 0 && reducedExtension ? "this " : "") +
            p.Type.ToDisplayString(TypeFormat) + " p" + i).ToList();
        if (!target.IsStatic) parameters.Insert(0, "this " + owner.ToDisplayString(TypeFormat) + " receiver");
        body.Append("(").Append(string.Join(", ", parameters)).Append(")");
        if (genericEf)
        {
            foreach (var p in target.TypeParameters)
            {
                var constraints = new List<string>();
                if (p.HasUnmanagedTypeConstraint) constraints.Add("unmanaged");
                else if (p.HasValueTypeConstraint) constraints.Add("struct");
                else if (p.HasReferenceTypeConstraint) constraints.Add("class");
                else if (p.HasNotNullConstraint) constraints.Add("notnull");
                constraints.AddRange(p.ConstraintTypes.Select(t => t.ToDisplayString(TypeFormat)));
                if (p.HasConstructorConstraint && !p.HasValueTypeConstraint) constraints.Add("new()");
                if (constraints.Count > 0) body.Append(" where ").Append(p.Name).Append(" : ").Append(string.Join(", ", constraints));
            }
        }
        var invocation = (target.IsStatic ? owner.ToDisplayString(TypeFormat) : "receiver") + ".@" + target.Name + args +
            "(" + string.Join(", ", target.Parameters.Select((_, i) => "p" + i)) + ")";
        var forward = target.ReturnsVoid ? invocation + "; return;" : "return " + invocation + ";";
        body.AppendLine(" {").Append("var timing = ").Append(Timing).AppendLine(".Current;")
            .Append("if (timing == null) { ").Append(forward).AppendLine(" }")
            .AppendLine("var start = global::System.Diagnostics.Stopwatch.GetTimestamp();");
        if (asynchronous)
            body.Append(awaited ? "return timing.CompleteStep(\"" : "return timing.ObserveStep(\"")
                .Append(label).Append("\", start, ").Append(invocation).AppendLine(");");
        else
            body.Append("try { ").Append(forward).Append(" } finally { timing.EndStep(\"").Append(label)
                .AppendLine("\", start); }");
        return body.AppendLine("}").ToString();
    }
}
