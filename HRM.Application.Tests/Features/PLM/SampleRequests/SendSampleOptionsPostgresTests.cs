namespace HRM.Application.Tests.Features.PLM.SampleRequests;

public sealed class SendSampleOptionsPostgresTests(IsolatedGroupStoragePostgres postgres) : IClassFixture<IsolatedGroupStoragePostgres>
{
    [PostgresGroupStorageFact]
    public async Task ValidatesAllOptionsBeforeWritingThenSendsAndReplaysExactlyOneBatch()
    {
        await using var connection = await postgres.OpenAsync();
        await using var db = new ApplicationDbContext(new DbContextOptionsBuilder<ApplicationDbContext>().UseNpgsql(connection).Options);
        foreach (var name in new[] { "SampleRequest", "SampleRequestSampleTrial", "SampleRequestWorkflowEvent", "Formula", "Product", "Customer", "Employee",
            "Category", "FormulaVersion", "FormulaVersionItem", "FormulaMaterial", "ProductPricingVersion", "InternalMessage", "InternalConversation", "OutboxMessage", "AuditLog" })
            await SampleDeliveryOptionsPostgresTests.CreateTable(connection, db.Model.GetEntityTypes().Single(e => e.ClrType.Name == name));
        await using (var identity = new NpgsqlCommand("ALTER TABLE notification.outbox_messages ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY", connection))
            await identity.ExecuteNonQueryAsync();
        var user = new SampleTrialFeedbackCorrectionTests.User("LabUser"); var company = user.CompanyId!.Value; var employee = user.EmployeeId!.Value;
        var date = new DateTime(2026,11,14,8,0,0); var product = Guid.NewGuid(); var customer = Guid.NewGuid(); var category=Guid.NewGuid();
        db.Categories.Add(new Category { CategoryId=category, Name="Test" });
        db.Products.Add(new Product { ProductId=product,CategoryId=category,Name="Test",ColourCode="TEST",CompanyId=company,IsActive=true });
        db.Customers.Add(new Customer { CustomerId=customer,CompanyId=company,CustomerName="Test",IsActive=true });
        db.Employees.Add(new Employee { EmployeeId=employee,CompanyId=company,IsActive=true });
        var parent = new SampleRequest { SampleRequestId=Guid.NewGuid(),CompanyId=company,ProductId=product,CustomerId=customer,
            Status="InProgress",CreatedDate=date,UpdatedDate=date,SampleQuantity=5,InfoType="Thẻ mẫu",IsActive=true };
        var formulas = Enumerable.Range(1,2).Select(i=>new Formula { FormulaId=Guid.NewGuid(),ExternalId="VU_TEST_"+i,ProductId=product,CompanyId=company,Status=i==1?"Approved":"Draft",UpdatedDate=date,IsActive=true }).ToArray();
        db.SampleRequests.Add(parent);db.Formulas.AddRange(formulas);
        db.SampleRequestWorkflowEvents.Add(SampleRequestWorkflowEvents.Create(parent.SampleRequestId,company,employee,date,SampleRequestWorkflowEvents.FormulaConfirmed,formulaId:formulas[0].FormulaId));
        await db.SaveChangesAsync();db.ChangeTracker.Clear();
        var handler = new SendSampleOptionsCommandHandler(db,db,user,new CurrentUserPermissionService(user),SampleTrialFeedbackCorrectionTests.Visibility.Create(user),new Clock(),new FormulaVersionService(db,new KeyedMutationLock<Guid>()));
        var command = new SendSampleOptionsCommand { SampleRequestId=parent.SampleRequestId,BatchId=Guid.NewGuid(),ExpectedRequestUpdatedDate=date,SentDate=date,
            Options=formulas.Select((f,i)=>new SendSampleOption(f.FormulaId,i+2,date) { Note = i == 0 ? "Gửi theo hướng dẫn" : "" }).ToArray() };
        var confirmedPrimaryOptions = command.Options;
        command.Options = confirmedPrimaryOptions.Reverse().ToArray();
        Assert.False((await handler.Handle(command,default)).Success);
        db.ChangeTracker.Clear();Assert.Equal(0,await db.SampleRequestSampleTrials.CountAsync());Assert.Equal(0,await db.OutboxMessages.CountAsync());
        command.Options = confirmedPrimaryOptions;
        var sent=await handler.Handle(command,default);Assert.True(sent.Success,sent.Message);db.ChangeTracker.Clear();
        Assert.Equal(2,await db.SampleRequestSampleTrials.CountAsync());Assert.Equal(2,await db.FormulaVersions.CountAsync());Assert.Equal(1,await db.OutboxMessages.CountAsync());
        Assert.Equal("Gửi theo hướng dẫn", await db.SampleRequestSampleTrials.Where(t => t.FormulaId == formulas[0].FormulaId).Select(t => t.LabNote).SingleAsync());
        Assert.Equal("", await db.SampleRequestSampleTrials.Where(t => t.FormulaId == formulas[1].FormulaId).Select(t => t.LabNote).SingleAsync());
        Assert.Null(await db.Formulas.Where(f => f.FormulaId == formulas[0].FormulaId).Select(f => f.Note).SingleAsync());
        Assert.Equal(2,await db.SampleRequestWorkflowEvents.CountAsync(e=>e.EventType==SampleRequestWorkflowEvents.SampleSent&&e.RelatedEventId==command.BatchId));
        Assert.True((await handler.Handle(command,default)).Success);Assert.Equal(2,await db.SampleRequestSampleTrials.CountAsync());
        var originalOptions = command.Options;
        command.Options = originalOptions.Select(o => o with { Note = "Changed retry" }).ToArray();
        Assert.False((await handler.Handle(command, default)).Success);
        command.Options = originalOptions;
        command.Options=[new SendSampleOption(formulas[0].FormulaId,9,date)];Assert.False((await handler.Handle(command,default)).Success);
        Assert.Equal(1,await db.OutboxMessages.CountAsync());
    }
    private sealed class Clock:IDateTimeProvider { public DateTime Now=>new(2026,11,14,10,0,0); }
}
