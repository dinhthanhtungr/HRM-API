public sealed class LabNotesTests(IsolatedGroupStoragePostgres postgres) : IClassFixture<IsolatedGroupStoragePostgres>
{
    [Theory]
    [InlineData("SaleUser", true)]
    [InlineData("LabAdmin", false)]
    [InlineData("LabUser", false)]
    public async Task MissingTechnicalCapabilityOrAnonymousCannotWrite(string role, bool authenticated)
    {
        var user = new SampleTrialFeedbackCorrectionTests.User(role, authenticated);
        var handler = new RecordLabNoteCommandHandler(null!, user, new CurrentUserPermissionService(user), null!);
        Assert.False((await handler.Handle(new() { NoteId = Guid.NewGuid(), Note = "Shared note" }, default)).Success);
    }

    [PostgresGroupStorageFact]
    public async Task NotesPersistHistoryAndOutboxAtomicallyWithScopedReadRetryAndGeneralPublication()
    {
        await using var connection = await postgres.OpenAsync();
        await using var db = new ApplicationDbContext(new DbContextOptionsBuilder<ApplicationDbContext>().UseNpgsql(connection).Options);
        foreach (var type in new[] { typeof(SampleRequest), typeof(Employee), typeof(Customer), typeof(SampleRequestWorkflowEvent), typeof(OutboxMessage) })
        {
            var entity = db.Model.FindEntityType(type)!;
            var table = StoreObjectIdentifier.Table(entity.GetTableName()!, entity.GetSchema());
            var columns = entity.GetProperties().Select(p =>
            {
                var defaultSql = p.TryGetDefaultValue(out var value) && value is not null
                    ? " DEFAULT " + p.GetRelationalTypeMapping().GenerateSqlLiteral(value) : "";
                if (type == typeof(OutboxMessage) && p.Name == "Id") defaultSql = " GENERATED BY DEFAULT AS IDENTITY";
                return $"\"{p.GetColumnName(table)}\" {p.GetRelationalTypeMapping().StoreType}{defaultSql}";
            });
            var key = entity.FindPrimaryKey()!.Properties.Single().GetColumnName(table);
            // Trusted EF metadata only, in a verified disposable test cluster, never the application database.
            await using var create = new NpgsqlCommand($"CREATE SCHEMA IF NOT EXISTS \"{table.Schema}\"; CREATE TABLE \"{table.Schema}\".\"{table.Name}\" ({string.Join(',', columns)}, PRIMARY KEY (\"{key}\"));", connection);
            await create.ExecuteNonQueryAsync();
        }
        var lab = new SampleTrialFeedbackCorrectionTests.User("LabUser");
        var customer = new Customer { CustomerId = Guid.NewGuid(), CompanyId = lab.CompanyId!.Value, ExternalId = "KH_LAB_NOTE", IsActive = true };
        var parent = new SampleRequest { SampleRequestId = Guid.NewGuid(), CompanyId = lab.CompanyId.Value, CustomerId = customer.CustomerId,
            Status = "InProgress", IsActive = true, CreatedDate = new(2026, 10, 1), UpdatedDate = new(2026, 11, 5), FormulaId = Guid.NewGuid() };
        db.Customers.Add(customer); db.SampleRequests.Add(parent);
        db.Employees.Add(new Employee { EmployeeId = lab.EmployeeId!.Value, CompanyId = lab.CompanyId.Value, IsActive = true, FullName = "Lab author" });
        await db.SaveChangesAsync(); db.ChangeTracker.Clear();
        var visibility = SampleTrialFeedbackCorrectionTests.Visibility.Create(lab);
        var handler = new RecordLabNoteCommandHandler(db, lab, new CurrentUserPermissionService(lab), visibility);
        var first = new RecordLabNoteCommand { SampleRequestId = parent.SampleRequestId, NoteId = Guid.NewGuid(), Note = " First shared note ", ExpectedUpdatedDate = parent.UpdatedDate };
        Assert.True((await handler.Handle(first, default)).Success);
        Assert.True((await handler.Handle(first, default)).Success);
        Assert.Equal(1, await db.SampleRequestWorkflowEvents.CountAsync());
        Assert.Equal(1, await db.OutboxMessages.CountAsync());
        var stored = await db.SampleRequests.AsNoTracking().SingleAsync();
        Assert.Equal(parent.FormulaId, stored.FormulaId); Assert.Equal(parent.Status, stored.Status);
        Assert.False((await handler.Handle(new() { SampleRequestId = parent.SampleRequestId, NoteId = Guid.NewGuid(), Note = "Stale", ExpectedUpdatedDate = first.ExpectedUpdatedDate }, default)).Success);
        Assert.True((await handler.Handle(new() { SampleRequestId = parent.SampleRequestId, NoteId = Guid.NewGuid(), Note = "Second shared note", ExpectedUpdatedDate = stored.UpdatedDate }, default)).Success);
        Assert.Equal(2, await db.SampleRequestWorkflowEvents.CountAsync());
        Assert.Equal(2, await db.OutboxMessages.CountAsync());
        var read = new GetLabNotesQueryHandler(db, lab, new CurrentUserPermissionService(lab), visibility);
        var page = await read.Handle(new(parent.SampleRequestId), default);
        Assert.True(page!.CanWrite); Assert.Equal(2, page.Items.Count);
        Assert.Equal("Second shared note", page.Items[0].Note); Assert.Equal("First shared note", page.Items[1].Note);
        Assert.Equal("Lab author", page.Items[0].RecordedBy);
        var sale = new SameCompanySale(lab.CompanyId.Value);
        Assert.False((await new RecordLabNoteCommandHandler(db, sale, new CurrentUserPermissionService(sale), visibility).Handle(first, default)).Success);
        var salePage = await new GetLabNotesQueryHandler(db, sale, new CurrentUserPermissionService(sale), visibility).Handle(new(parent.SampleRequestId), default);
        Assert.Equal(2, salePage!.Items.Count); Assert.False(salePage.CanWrite);
        var outsider = new SampleTrialFeedbackCorrectionTests.User("LabUser");
        Assert.Null(await new GetLabNotesQueryHandler(db, outsider, new CurrentUserPermissionService(outsider), SampleTrialFeedbackCorrectionTests.Visibility.Create(outsider)).Handle(new(parent.SampleRequestId), default));
        var sender = DispatchProxy.Create<ISender, SamplePriceFeedbackPublicationTests.CaptureSender>();
        var dispatch = new DispatchSampleRequestWorkflowNotificationCommandHandler(db, sender, null!, null!);
        var job = await db.OutboxMessages.OrderBy(x => x.Id).FirstAsync();
        Assert.True((await dispatch.Handle(new(job.Id), default)).Success);
        Assert.True((await dispatch.Handle(new(job.Id), default)).Success);
        var message = Assert.Single(((SamplePriceFeedbackPublicationTests.CaptureSender)sender).Commands);
        Assert.Equal(SampleRequestNotificationType.GeneralMessage, message.Type);
        Assert.Equal(TopicNotifications.SampleRequestLabNoteRecorded, message.TopicOverride);
        Assert.Contains("First shared note", message.Message);
        Assert.True(SampleRequestWorkflowPublicationRules.ShouldDispatch(parent.CreatedDate, SampleRequestWorkflowEvents.LabNote));
        Assert.True(SampleRequestWorkflowPublicationRules.IsTrustedPublication(await db.SampleRequestWorkflowEvents.FindAsync(first.NoteId), parent.SampleRequestId, lab.CompanyId.Value, lab.EmployeeId.Value, true));
        // Notes may be shared on readable records even when the actor has no workflow ownership.
        foreach (var role in new[] { "LabUser", "Developer", "President", "LabUser,SaleAdmin" })
        {
            var author = new SameCompanySale(lab.CompanyId.Value, role);
            db.Employees.Add(new Employee { EmployeeId = author.EmployeeId!.Value, CompanyId = lab.CompanyId.Value,
                IsActive = true, FullName = role });
            await db.SaveChangesAsync(); db.ChangeTracker.Clear();
            var readable = ReadOnlyScope.Create(author);
            var authorPage = await new GetLabNotesQueryHandler(db, author, new CurrentUserPermissionService(author), readable)
                .Handle(new(parent.SampleRequestId), default);
            Assert.True(authorPage!.CanWrite);
            Assert.True((await new RecordLabNoteCommandHandler(db, author, new CurrentUserPermissionService(author), readable)
                .Handle(new() { SampleRequestId = parent.SampleRequestId, NoteId = Guid.NewGuid(), Note = role + " shared note",
                    ExpectedUpdatedDate = authorPage.ExpectedUpdatedDate }, default)).Success);
        }
        await db.SampleRequests.ExecuteUpdateAsync(set => set.SetProperty(x => x.Status, "Completed"));
        var token = (await db.SampleRequests.AsNoTracking().SingleAsync()).UpdatedDate;
        Assert.False((await handler.Handle(new() { SampleRequestId = parent.SampleRequestId, NoteId = Guid.NewGuid(), Note = "Cannot update closed request", ExpectedUpdatedDate = token }, default)).Success);
        Assert.False((await read.Handle(new(parent.SampleRequestId), default))!.CanWrite);
    }

    public class ReadOnlyScope : DispatchProxy
    {
        private HRM.Application.Abstractions.Security.ICurrentUser _user = null!;
        public static HRM.Application.Features.CRM.CustomerCare.Visibility.ICustomerVisibilityService Create(
            HRM.Application.Abstractions.Security.ICurrentUser user)
        {
            var service = Create<HRM.Application.Features.CRM.CustomerCare.Visibility.ICustomerVisibilityService, ReadOnlyScope>();
            ((ReadOnlyScope)service)._user = user;
            return service;
        }
        protected override object? Invoke(MethodInfo? method, object?[]? args) => method!.Name switch
        {
            "BuildReadScopeAsync" => Task.FromResult(new ViewerScope(
                _user.CompanyId!.Value, _user.EmployeeId!.Value, true, false, new HashSet<Guid>(), new HashSet<Guid>(), DateTime.Now)),
            "ApplySampleRequestVisibility" => args![0],
            _ => throw new InvalidOperationException("Notes must not require technical workflow write scope: " + method.Name)
        };
    }

    private sealed class SameCompanySale(Guid company, string roles = "SaleUser") : HRM.Application.Abstractions.Security.ICurrentUser
    {
        public bool IsAuthenticated => true;
        public Guid UserId { get; } = Guid.NewGuid();
        public Guid? EmployeeId { get; } = Guid.NewGuid();
        public Guid? CompanyId => company;
        public string? UserName => null;
        public string? Email => null;
        public IReadOnlyCollection<string> Roles => roles.Split(',');
        public bool IsInRole(string role) => Roles.Contains(role);
    }
}
