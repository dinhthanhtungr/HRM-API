public sealed class SampleFollowUpDeliveryPostgresTests(IsolatedGroupStoragePostgres postgres)
    : IClassFixture<IsolatedGroupStoragePostgres>
{
    [PostgresGroupStorageFact]
    public async Task CancelledOldRequestCanPlanThenSendChipAndKgWithoutRecreatingTheRequest()
    {
        await using var connection = await postgres.OpenAsync();
        var failures = new SaveFailure();
        await using var db = new ApplicationDbContext(new DbContextOptionsBuilder<ApplicationDbContext>().UseNpgsql(connection).AddInterceptors(failures).Options);
        foreach (var name in new[] { "SampleRequest", "SampleRequestSampleTrial", "Formula", "ProductPricingVersion", "Employee", "Customer",
            "Product", "Category", "SampleRequestWorkflowEvent", "FormulaVersion", "FormulaVersionItem", "FormulaMaterial", "InternalMessage", "InternalConversation", "OutboxMessage", "AuditLog" })
        {
            var entity = db.Model.GetEntityTypes().Single(x => x.ClrType.Name == name);
            await CreateTable(connection, entity);
            var table = StoreObjectIdentifier.Table(entity.GetTableName()!, entity.GetSchema());
            foreach (var property in entity.GetProperties().Where(p => p.GetDefaultValue() is bool))
            {
                // Fixture tables mirror the EF boolean defaults used by real inserts.
                await using var defaults = new NpgsqlCommand($"ALTER TABLE \"{table.Schema}\".\"{table.Name}\" ALTER COLUMN \"{property.GetColumnName(table)}\" SET DEFAULT {(property.GetDefaultValue() is true ? "TRUE" : "FALSE")}", connection);
                await defaults.ExecuteNonQueryAsync();
            }
        }
        await using (var identity = new NpgsqlCommand("ALTER TABLE notification.outbox_messages ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY", connection))
            await identity.ExecuteNonQueryAsync();
        var actor = new SampleTrialFeedbackCorrectionTests.User("LabUser");
        var company = actor.CompanyId!.Value; var employee = actor.EmployeeId!.Value;
        var requestId = Guid.NewGuid(); var formulaId = Guid.NewGuid(); var productId = Guid.NewGuid(); var customerId = Guid.NewGuid(); var categoryId = Guid.NewGuid();
        var original = new DateTime(2026, 11, 2, 8, 0, 0);
        foreach (var (name, values) in new (string, Dictionary<string, object?>)[]
        {
            ("Employee", new() { ["EmployeeId"] = employee, ["CompanyId"] = company, ["IsActive"] = true }),
            ("Customer", new() { ["CustomerId"] = customerId, ["CompanyId"] = company, ["IsActive"] = true, ["IsLead"] = true }),
            ("Category", new() { ["CategoryId"] = categoryId, ["CompanyId"] = company, ["IsActive"] = true }),
            ("Product", new() { ["ProductId"] = productId, ["CategoryId"] = categoryId, ["CompanyId"] = company, ["IsActive"] = true }),
            ("Formula", new() { ["FormulaId"] = formulaId, ["ProductId"] = productId, ["CompanyId"] = company, ["IsActive"] = true,
                ["Status"] = "Approved", ["ExternalId"] = "VU-sequential", ["CreatedDate"] = original, ["UpdatedDate"] = original }),
            ("SampleRequest", new() { ["SampleRequestId"] = requestId, ["CompanyId"] = company, ["CustomerId"] = customerId,
                ["ProductId"] = productId, ["FormulaId"] = formulaId, ["ManagerBy"] = employee, ["Status"] = "Cancelled",
                ["InfoType"] = "Thẻ màu (1)", ["SampleQuantity"] = 100d, ["CreatedDate"] = new DateTime(2024, 10, 31), ["UpdatedDate"] = original, ["IsActive"] = true }),
            ("SampleRequestWorkflowEvent", new() { ["Id"] = Guid.NewGuid(), ["CompanyId"] = company, ["SampleRequestId"] = requestId,
                ["FormulaId"] = formulaId, ["EventType"] = SampleRequestWorkflowEvents.FormulaConfirmed, ["RecordedAt"] = original })
        }) await Insert(connection, db.Model.GetEntityTypes().Single(x => x.ClrType.Name == name), values);
        var historicalFormulaId = Guid.NewGuid();
        var historicalDate = new DateTime(2024, 11, 1);
        await Insert(connection, db.Model.FindEntityType(typeof(Formula))!, new() { ["FormulaId"] = historicalFormulaId,
            ["ProductId"] = productId, ["CompanyId"] = company, ["IsActive"] = true, ["IsSelect"] = true,
            ["Status"] = "Completed", ["CreatedDate"] = historicalDate, ["UpdatedDate"] = historicalDate });
        foreach (var no in new[] { 1, 2 })
            await Insert(connection, db.Model.FindEntityType(typeof(SampleRequestSampleTrial))!, new() {
                ["SampleRequestSampleTrialId"] = Guid.NewGuid(), ["SampleRequestId"] = requestId,
                ["FormulaId"] = historicalFormulaId, ["TrialNo"] = no, ["IsActive"] = true,
                ["Status"] = (int)SampleTrialStatus.Approved, ["DeliveredSampleQuantityKg"] = no == 1 ? null : 2m,
                ["SentDate"] = historicalDate, ["CreatedDate"] = historicalDate, ["UpdatedDate"] = historicalDate,
                ["CustomerReplyDate"] = historicalDate, ["CustomerReplyNote"] = "Historical feedback" });
        var visibility = SampleManagedSaleWorkflowPostgresTests.ScopedVisibility.Create(new ViewerScope(company, employee, true, false, new HashSet<Guid>(), new HashSet<Guid>(), DateTime.Now));
        var versions = new FormulaVersionService(db, new KeyedMutationLock<Guid>());
        var sale = new SampleWorkflowMutationTestSupport.Actor(company, Guid.NewGuid(), ApplicationRoles.Developer);
        await Insert(connection, db.Model.FindEntityType(typeof(HRM.Domain.Entities.HrSchema.Employee))!, new()
            { ["EmployeeId"] = sale.EmployeeId, ["CompanyId"] = company, ["IsActive"] = true });
        var followUp = new ApplySampleFlowActionCommandHandler(db, sale, new CurrentUserPermissionService(sale),
            SampleWorkflowMutationTestSupport.Visibility.Create(sale), versions, null!, db);
        var planCommand = new ApplySampleFlowActionCommand { SampleRequestId = requestId, Action = ChipThenSampleRules.Action,
            RequestedKg = 100, RequestedSets = 1, Note = "New customer request after cancellation",
            ExpectedUpdatedDate = original, ExpectedFormulaUpdatedDate = original };
        var outsider = new SampleWorkflowMutationTestSupport.Actor(company, Guid.NewGuid(), ApplicationRoles.Sales.SaleUser);
        await Insert(connection, db.Model.FindEntityType(typeof(HRM.Domain.Entities.HrSchema.Employee))!, new()
            { ["EmployeeId"] = outsider.EmployeeId, ["CompanyId"] = company, ["IsActive"] = true });
        var unauthorized = new ApplySampleFlowActionCommandHandler(db, outsider, new CurrentUserPermissionService(outsider),
            SampleWorkflowMutationTestSupport.Visibility.Create(outsider), versions, null!, db);
        Assert.False((await unauthorized.Handle(planCommand, default)).Success);
        Assert.Equal(0, await db.SampleRequestWorkflowEvents.CountAsync(e => e.EventType == SampleFollowUpRules.Started));
        db.ChangeTracker.Clear();
        var foreignDev = new SampleWorkflowMutationTestSupport.Actor(Guid.NewGuid(), Guid.NewGuid(), ApplicationRoles.Developer);
        await Insert(connection, db.Model.FindEntityType(typeof(HRM.Domain.Entities.HrSchema.Employee))!, new()
            { ["EmployeeId"] = foreignDev.EmployeeId, ["CompanyId"] = foreignDev.CompanyId, ["IsActive"] = true });
        var foreignHandler = new ApplySampleFlowActionCommandHandler(db, foreignDev, new CurrentUserPermissionService(foreignDev),
            SampleWorkflowMutationTestSupport.Visibility.Create(foreignDev), versions, null!, db);
        Assert.False((await foreignHandler.Handle(planCommand, default)).Success);
        db.ChangeTracker.Clear();
        var planned = await followUp.Handle(planCommand, default);
        Assert.True(planned.Success, planned.Message);
        db.ChangeTracker.Clear();
        var reopened = await db.SampleRequests.AsNoTracking().SingleAsync(x => x.SampleRequestId == requestId);
        Assert.Equal("InProgress", reopened.Status);
        Assert.Equal(new DateTime(2024, 10, 31), reopened.CreatedDate);
        Assert.Equal(productId, reopened.ProductId);
        Assert.Equal(1, await db.SampleRequestWorkflowEvents.CountAsync(e => e.EventType == SampleFollowUpRules.Started));
        Assert.Equal(1, await SampleRequestWorkScope.Apply(db.SampleRequests, db.SampleRequestWorkflowEvents).CountAsync());
        Assert.Equal(2, await db.SampleRequestSampleTrials.CountAsync());
        var reportRows = db.SampleRequests.Where(x => x.SampleRequestId == requestId).Select(x => new SampleRequestSampleTrialReportRow {
            SampleRequest = x, ConfirmedFormulaId = x.FormulaId, Trial = db.SampleRequestSampleTrials.Where(t => t.SampleRequestId == x.SampleRequestId && t.IsActive)
                .OrderByDescending(t => t.TrialNo).FirstOrDefault() });
        var facts = await SampleWorkDecisionQuery.ReadFacts(reportRows, db, db, "VND")
            .Select(x => new { x.Facts.Legacy, x.Facts.DeliveryRequested, x.Facts.ChipFirstPending }).SingleAsync();
        Assert.False(facts.Legacy); Assert.True(facts.DeliveryRequested); Assert.False(facts.ChipFirstPending);
        Assert.False((await followUp.Handle(planCommand, default)).Success);
        db.ChangeTracker.Clear();
        var handler = new UpdateFormulaStatusCommandHandler(db, actor, new FormulaWriteService(db, null!), versions, null!,
            new FormulaPricingReviewService(db, db, null!), visibility, null!, new CurrentUserPermissionService(actor), db);
        async Task<HRM.Application.Commons.Models.OperationResult<HRM.Application.Features.PLM.Formulas.Dtos.Commons.FormulaWriteResultDto>> Send(decimal? quantity)
        {
            db.ChangeTracker.Clear();
            var formula = await db.Formulas.AsNoTracking().SingleAsync(x => x.FormulaId == formulaId);
            return await handler.Handle(new(formulaId, new UpdateFormulaStatusRequest { SampleRequestId = requestId,
                Status = FormulaStatus.SampleSent, DeliveredSampleQuantityKg = quantity, ExpectedUpdatedDate = formula.UpdatedDate }), default);
        }
        planCommand.ExpectedUpdatedDate = reopened.UpdatedDate;
        Assert.False((await followUp.Handle(planCommand, default)).Success);
        Assert.Equal(1, await db.SampleRequestWorkflowEvents.CountAsync(e => e.EventType == SampleFlowRules.ChipThenSampleRequested));
        Assert.False((await Send(null)).Success); // Combined delivery requires actual kg, not a separate chip confirmation.
        db.ChangeTracker.Clear();
        var beforeBatch = await db.SampleRequests.AsNoTracking().SingleAsync(x => x.SampleRequestId == requestId);
        var chipFormula = await db.Formulas.AsNoTracking().SingleAsync(x => x.FormulaId == formulaId);
        var sentAt = DateTime.Now;
        sentAt = sentAt.AddTicks(-(sentAt.Ticks % 10));
        var batchCommand = new SendSampleOptionsCommand { SampleRequestId = requestId, BatchId = Guid.NewGuid(),
            SentDate = sentAt, ExpectedRequestUpdatedDate = beforeBatch.UpdatedDate,
            Options = [new SendSampleOption(formulaId, 100, chipFormula.UpdatedDate ?? chipFormula.CreatedDate ?? original)] };
        var batchHandler = new SendSampleOptionsCommandHandler(db, db, actor, new CurrentUserPermissionService(actor), visibility, new Clock(), versions);
        var sample = await batchHandler.Handle(batchCommand, default);
        Assert.True(sample.Success, sample.Message + failures.Error);
        db.ChangeTracker.Clear();
        var replay = await batchHandler.Handle(batchCommand, default);
        Assert.True(replay.Success, replay.Message);
        Assert.Equal(1, await db.SampleRequestWorkflowEvents.CountAsync(e => e.EventType == SampleDeliveryRules.BatchSent));
        var deliveries = await new GetSampleDeliveriesQueryHandler(db, actor, new CurrentUserPermissionService(actor), visibility)
            .Handle(new GetSampleDeliveriesQuery(requestId), default);
        Assert.Single(Assert.Single(deliveries!.Batches).Options); // Chip is separate from kg option feedback.
        var rounds = await db.SampleRequestSampleTrials.AsNoTracking().OrderBy(x => x.TrialNo).ToArrayAsync();
        Assert.Equal(4, rounds.Length);
        Assert.Null(rounds[0].DeliveredSampleQuantityKg);
        Assert.Equal(2m, rounds[1].DeliveredSampleQuantityKg);
        Assert.All(rounds.Take(2), t => { Assert.Equal(historicalFormulaId, t.FormulaId); Assert.Equal(historicalDate, t.SentDate);
            Assert.Equal(historicalDate, t.CustomerReplyDate); Assert.Equal("Historical feedback", t.CustomerReplyNote); });
        var historicalFormula = await db.Formulas.AsNoTracking().SingleAsync(f => f.FormulaId == historicalFormulaId);
        Assert.Equal("Completed", historicalFormula.Status); Assert.True(historicalFormula.IsSelect);
        Assert.Equal(historicalDate, historicalFormula.UpdatedDate);
        Assert.Equal(0m, rounds[2].DeliveredSampleQuantityKg); Assert.Equal(100m, rounds[3].DeliveredSampleQuantityKg);
        Assert.All(rounds.Skip(2), t => { Assert.Equal(requestId, t.SampleRequestId); Assert.Equal(formulaId, t.FormulaId); Assert.Null(t.CustomerReplyDate); });
        Assert.Equal(1, await db.SampleRequests.CountAsync());
        Assert.False((await Send(100)).Success);
        Assert.Equal(4, await db.SampleRequestSampleTrials.CountAsync());
        Assert.Equal(1, await ChipThenSampleRules.OptionalChips(db.SampleRequestSampleTrials).CountAsync());
        Assert.Equal(1, await ChipThenSampleRules.PlannedChips(db.SampleRequestSampleTrials, db.SampleRequestWorkflowEvents).CountAsync());
        Assert.Equal(1, await ChipThenSampleRules.BlockingPending(db.SampleRequestSampleTrials).CountAsync());

        // A new explicit kg request does not invent feedback or finish the previous delivery.
        var beforeRepeat = await db.SampleRequests.AsNoTracking().SingleAsync();
        var pendingSnapshot = rounds[3];
        var saleFlow = await SampleFlowStateReader.ReadAsync(db, db, beforeRepeat, false, true, default);
        Assert.Contains("RequestSample", saleFlow.PlanActions);
        var repeat = new ApplySampleFlowActionCommand { SampleRequestId = requestId, Action = "RequestSample",
            RequestedKg = 100, Note = "Customer requests another sample; previous reply is unknown",
            ExpectedUpdatedDate = beforeRepeat.UpdatedDate };
        var requested = await followUp.Handle(repeat, default);
        Assert.True(requested.Success, requested.Message);
        Assert.Equal(requestId, requested.Data);
        db.ChangeTracker.Clear();
        Assert.False((await followUp.Handle(repeat, default)).Success);
        db.ChangeTracker.Clear();
        repeat.ExpectedUpdatedDate = (await db.SampleRequests.AsNoTracking().SingleAsync()).UpdatedDate;
        Assert.False((await followUp.Handle(repeat, default)).Success); // unsent duplicate plan
        db.ChangeTracker.Clear();
        Assert.Equal(0, await ChipThenSampleRules.BlockingPending(db.SampleRequestSampleTrials).CountAsync());
        var repeatFacts = await SampleWorkDecisionQuery.ReadFacts(reportRows, db, db, "VND")
            .Select(x => new { x.Facts.DeliveryRequested, x.Facts.PendingTrial }).SingleAsync();
        Assert.True(repeatFacts.DeliveryRequested); Assert.False(repeatFacts.PendingTrial);
        var nextFormulaId = Guid.NewGuid();
        await Insert(connection, db.Model.FindEntityType(typeof(Formula))!, new() { ["FormulaId"] = nextFormulaId,
            ["ProductId"] = productId, ["CompanyId"] = company, ["IsActive"] = true,
            ["Status"] = "Approved", ["CreatedDate"] = original, ["UpdatedDate"] = original });
        var repeatRequest = await db.SampleRequests.AsNoTracking().SingleAsync();
        var labFlow = await SampleFlowStateReader.ReadAsync(db, db, repeatRequest, true, false, default, nextFormulaId);
        Assert.Contains("Send", labFlow.AllowedActions);
        var nextBatch = await batchHandler.Handle(new SendSampleOptionsCommand { SampleRequestId = requestId,
            BatchId = Guid.NewGuid(), SentDate = sentAt, ExpectedRequestUpdatedDate = repeatRequest.UpdatedDate,
            Options = [new SendSampleOption(nextFormulaId, 100, original)] }, default);
        Assert.True(nextBatch.Success, nextBatch.Message + failures.Error);
        db.ChangeTracker.Clear();
        var unchanged = await db.SampleRequestSampleTrials.AsNoTracking().SingleAsync(t =>
            t.SampleRequestSampleTrialId == pendingSnapshot.SampleRequestSampleTrialId);
        Assert.Equal(pendingSnapshot.Status, unchanged.Status);
        Assert.Equal(pendingSnapshot.UpdatedDate, unchanged.UpdatedDate);
        Assert.Equal(pendingSnapshot.SentDate, unchanged.SentDate);
        Assert.Null(unchanged.CustomerReplyDate); Assert.Equal(pendingSnapshot.CustomerReplyNote, unchanged.CustomerReplyNote);
        Assert.Equal(5, await db.SampleRequestSampleTrials.CountAsync());
        Assert.Equal(1, await db.SampleRequests.CountAsync());
        Assert.Equal(productId, (await db.SampleRequests.AsNoTracking().SingleAsync()).ProductId);
        Assert.Equal(1, await ChipThenSampleRules.BlockingPending(db.SampleRequestSampleTrials).CountAsync());
    }

    private sealed class Clock : IDateTimeProvider { public DateTime Now => DateTime.Now; }

    private sealed class SaveFailure : Microsoft.EntityFrameworkCore.Diagnostics.SaveChangesInterceptor
    {
        internal string? Error { get; private set; }
        public override Task SaveChangesFailedAsync(Microsoft.EntityFrameworkCore.Diagnostics.DbContextErrorEventData eventData, CancellationToken cancellationToken = default)
        {
            Error = eventData.Exception.ToString();
            return Task.CompletedTask;
        }
    }
}

