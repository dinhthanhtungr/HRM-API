    public sealed class QaClock : IDateTimeProvider { public DateTime Now => DateTime.Now; }
    public sealed class QaUser(IHttpContextAccessor accessor) : ICurrentUser
    {
        private ClaimsPrincipal Principal => accessor.HttpContext!.User;
        public bool IsAuthenticated => Principal.Identity?.IsAuthenticated == true;
        public Guid UserId => EmployeeId ?? Guid.Empty;
        public Guid? EmployeeId => Principal.IsInRole("LabUser") ? Lab : Sale;
        public Guid? CompanyId => Principal.IsInRole("ForeignSale") ? Guid.Parse("90000000-0000-0000-0000-000000000001") : Company;
        public string? UserName => "synthetic-browser-qa";
        public string? Email => null;
        public IReadOnlyCollection<string> Roles => Principal.FindAll(ClaimTypes.Role).Select(c => c.Value).ToArray();
        public bool IsInRole(string role) => Principal.IsInRole(role);
    }
    public sealed class QaAuth(IOptionsMonitor<AuthenticationSchemeOptions> options, ILoggerFactory logger, UrlEncoder encoder) : AuthenticationHandler<AuthenticationSchemeOptions>(options, logger, encoder)
    {
        protected override Task<AuthenticateResult> HandleAuthenticateAsync()
        {
            var role = Request.Headers["X-QA-Role"].ToString();
            if (role is not ("LabUser" or "SaleUser" or "ForeignSale")) return Task.FromResult(AuthenticateResult.NoResult());
            var claims = new[] { new Claim(ClaimTypes.Name, "synthetic-browser-qa"), new Claim(ClaimTypes.Role, role == "ForeignSale" ? "SaleUser" : role) }.ToList();
            if (role == "ForeignSale") claims.Add(new Claim(ClaimTypes.Role, "ForeignSale"));
            return Task.FromResult(AuthenticateResult.Success(new AuthenticationTicket(new ClaimsPrincipal(new ClaimsIdentity(claims, Scheme.Name)), Scheme.Name)));
        }
    }
    public class QaVisibility : DispatchProxy
    {
        private ICurrentUser user = null!;
        public static ICustomerVisibilityService Create(ICurrentUser user) { var proxy = Create<ICustomerVisibilityService, QaVisibility>(); ((QaVisibility)proxy).user = user; return proxy; }
        protected override object? Invoke(MethodInfo? method, object?[]? args) => method!.Name switch {
            "BuildScopeAsync" or "BuildReadScopeAsync" => Task.FromResult(new ViewerScope(user.CompanyId!.Value, user.EmployeeId!.Value, true, false, new HashSet<Guid>(), new HashSet<Guid>(), DateTime.Now)),
            "ApplySampleRequestVisibility" => ((IQueryable<SampleRequest>)args![0]!).Where(r => r.CompanyId == user.CompanyId),
            "ApplyCustomerVisibility" => ((IQueryable<Customer>)args![0]!).Where(r => r.CompanyId == user.CompanyId),
            _ => throw new NotSupportedException(method.Name)
        };
    }
    public sealed class BrowserQaFactAttribute : FactAttribute
    {
        public BrowserQaFactAttribute() { if (Environment.GetEnvironmentVariable("HRM_SAMPLE_DELIVERY_BROWSER_QA") != "1" || IsolatedGroupStoragePostgres.BinaryDirectory is null) Skip = "Opt-in local browser QA only; requires fresh isolated PostgreSQL."; }
    }
