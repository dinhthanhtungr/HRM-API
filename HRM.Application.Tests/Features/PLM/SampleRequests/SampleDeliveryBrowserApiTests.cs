    internal static readonly Guid Lab = Guid.Parse("10000000-0000-0000-0000-000000000002");
    internal static readonly Guid Sale = Guid.Parse("10000000-0000-0000-0000-000000000003");
    internal static readonly Guid Request = Guid.Parse("10000000-0000-0000-0000-000000000004");

    [BrowserQaFact]
    public async Task RealHttpApiWithIsolatedPostgresForBrowserVerification()
    {
        await using (var connection = await postgres.OpenAsync())
        await using (var db = new ApplicationDbContext(new DbContextOptionsBuilder<ApplicationDbContext>().UseNpgsql(connection).Options))
        {
            foreach (var name in new[] { "SampleRequest", "SampleRequestSampleTrial", "SampleRequestWorkflowEvent", "Formula", "Product", "Customer", "Employee", "Category", "FormulaVersion", "FormulaVersionItem", "FormulaMaterial", "ProductPricingVersion", "InternalMessage", "InternalConversation", "OutboxMessage", "AuditLog", "CustomerInteraction", "CustomerInteractionReference" })
                await SampleDeliveryOptionsPostgresTests.CreateTable(connection, db.Model.GetEntityTypes().Single(e => e.ClrType.Name == name));
            await using (var identity = new NpgsqlCommand("ALTER TABLE notification.outbox_messages ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY", connection))
                await identity.ExecuteNonQueryAsync();
            var now = DateTime.Now.AddMinutes(-2); var product = Guid.NewGuid(); var customer = Guid.NewGuid(); var category = Guid.NewGuid();
            db.Categories.Add(new Category { CategoryId = category, Name = "Browser QA" });
            db.Products.Add(new Product { ProductId = product, CategoryId = category, Name = "Synthetic browser sample", ColourCode = "QA", CompanyId = Company, IsActive = true });
            db.Customers.Add(new Customer { CustomerId = customer, CompanyId = Company, CustomerName = "Synthetic QA customer", IsActive = true });
            db.Employees.AddRange(new Employee { EmployeeId = Lab, CompanyId = Company, IsActive = true }, new Employee { EmployeeId = Sale, CompanyId = Company, IsActive = true });
            db.SampleRequests.Add(new SampleRequest { SampleRequestId = Request, ExternalId = "TP_BROWSER_QA", CompanyId = Company, ManagerBy = Sale, ProductId = product, CustomerId = customer, Status = "InProgress", CreatedDate = now, UpdatedDate = now, SampleQuantity = 9, InfoType = "Thẻ mẫu", IsActive = true });
            foreach (var i in Enumerable.Range(1, 3))
            {
                var formula = new Formula { FormulaId = Guid.Parse($"20000000-0000-0000-0000-{i:000000000000}"), ExternalId = $"VU_QA_{i}", ProductId = product, CompanyId = Company, Status = "Approved", CreatedDate = now, UpdatedDate = now, IsActive = true };
                db.Formulas.Add(formula);
                db.SampleRequestWorkflowEvents.Add(SampleRequestWorkflowEvents.Create(Request, Company, Lab, now, SampleRequestWorkflowEvents.FormulaConfirmed, formulaId: formula.FormulaId));
            }
            await db.SaveChangesAsync();
