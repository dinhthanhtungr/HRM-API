        try { await stop.Task.WaitAsync(TimeSpan.FromMinutes(25)); }
        finally { await app.StopAsync(); }
        await using var checkConnection = await postgres.OpenAsync();
        await using var check = new ApplicationDbContext(new DbContextOptionsBuilder<ApplicationDbContext>().UseNpgsql(checkConnection).Options);
        Assert.Equal(3, await check.SampleRequestSampleTrials.CountAsync());
