public sealed class ChipThenSampleDeliveryPostgresTests(IsolatedGroupStoragePostgres postgres)
    : IClassFixture<IsolatedGroupStoragePostgres>
{
    [PostgresGroupStorageFact]
    public async Task ActualSendHandlerRecordsChipAndKgInOneConfirmationAndPreservesBothTrials()
    {
        await using var connection = await postgres.OpenAsync();
        var failures = new SaveFailure();
        await using var db = new ApplicationDbContext(new DbContextOptionsBuilder<ApplicationDbContext>().UseNpgsql(connection).AddInterceptors(failures).Options);
        foreach (var name in new[] { "SampleRequest", "SampleRequestSampleTrial", "Formula", "ProductPricingVersion", "Employee", "Customer",
            "Product", "Category", "SampleRequestWorkflowEvent", "FormulaVersion", "FormulaVersionItem", "FormulaMaterial", "InternalMessage", "InternalConversation", "OutboxMessage", "AuditLog" })
        {
            var entity = db.Model.GetEntityTypes().Single(x => x.ClrType.Name == name);
            await CreateTable(connection, entity);
            var table = StoreObjectIdentifier.Table(entity.GetTableName()!, entity.GetSchema());
            foreach (var property in entity.GetProperties().Where(p => p.GetDefaultValue() is bool))
            {
                // Fixture tables mirror the EF boolean defaults used by real inserts.
                await using var defaults = new NpgsqlCommand($"ALTER TABLE \"{table.Schema}\".\"{table.Name}\" ALTER COLUMN \"{property.GetColumnName(table)}\" SET DEFAULT {(property.GetDefaultValue() is true ? "TRUE" : "FALSE")}", connection);
                await defaults.ExecuteNonQueryAsync();
            }
        }
        await using (var identity = new NpgsqlCommand("ALTER TABLE notification.outbox_messages ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY", connection))
            await identity.ExecuteNonQueryAsync();
        var actor = new SampleTrialFeedbackCorrectionTests.User("LabUser");
        var company = actor.CompanyId!.Value; var employee = actor.EmployeeId!.Value;
        var requestId = Guid.NewGuid(); var formulaId = Guid.NewGuid(); var productId = Guid.NewGuid(); var customerId = Guid.NewGuid(); var categoryId = Guid.NewGuid();
        var original = new DateTime(2026, 11, 2, 8, 0, 0);
        foreach (var (name, values) in new (string, Dictionary<string, object?>)[]
        {
            ("Employee", new() { ["EmployeeId"] = employee, ["CompanyId"] = company, ["IsActive"] = true }),
            ("Customer", new() { ["CustomerId"] = customerId, ["CompanyId"] = company, ["IsActive"] = true, ["IsLead"] = true }),
            ("Category", new() { ["CategoryId"] = categoryId, ["CompanyId"] = company, ["IsActive"] = true }),
            ("Product", new() { ["ProductId"] = productId, ["CategoryId"] = categoryId, ["CompanyId"] = company, ["IsActive"] = true }),
            ("Formula", new() { ["FormulaId"] = formulaId, ["ProductId"] = productId, ["CompanyId"] = company, ["IsActive"] = true,
                ["Status"] = "Approved", ["ExternalId"] = "VU-sequential", ["CreatedDate"] = original, ["UpdatedDate"] = original }),
            ("SampleRequest", new() { ["SampleRequestId"] = requestId, ["CompanyId"] = company, ["CustomerId"] = customerId,
                ["ProductId"] = productId, ["FormulaId"] = formulaId, ["ManagerBy"] = employee, ["Status"] = "InProgress",
                ["InfoType"] = "Thẻ màu (1)", ["SampleQuantity"] = 100d, ["CreatedDate"] = original, ["UpdatedDate"] = original, ["IsActive"] = true }),
            ("SampleRequestWorkflowEvent", new() { ["Id"] = Guid.NewGuid(), ["CompanyId"] = company, ["SampleRequestId"] = requestId,
                ["FormulaId"] = formulaId, ["EventType"] = SampleFlowRules.ChipThenSampleRequested, ["RecordedAt"] = original })
        }) await Insert(connection, db.Model.GetEntityTypes().Single(x => x.ClrType.Name == name), values);
        var visibility = SampleManagedSaleWorkflowPostgresTests.ScopedVisibility.Create(new ViewerScope(company, employee, true, false, new HashSet<Guid>(), new HashSet<Guid>(), DateTime.Now));
        var versions = new FormulaVersionService(db, new KeyedMutationLock<Guid>());
        var handler = new UpdateFormulaStatusCommandHandler(db, actor, new FormulaWriteService(db, null!), versions, null!,
            new FormulaPricingReviewService(db, db, null!), visibility, null!, new CurrentUserPermissionService(actor), db);
        async Task<HRM.Application.Commons.Models.OperationResult<HRM.Application.Features.PLM.Formulas.Dtos.Commons.FormulaWriteResultDto>> Send(decimal? quantity)
        {
            db.ChangeTracker.Clear();
            var formula = await db.Formulas.AsNoTracking().SingleAsync(x => x.FormulaId == formulaId);
            return await handler.Handle(new(formulaId, new UpdateFormulaStatusRequest { SampleRequestId = requestId,
                Status = FormulaStatus.SampleSent, DeliveredSampleQuantityKg = quantity, ExpectedUpdatedDate = formula.UpdatedDate }), default);
        }
        Assert.False((await Send(null)).Success);
        var sample = await Send(100); Assert.True(sample.Success, sample.Message + failures.Error);
        var rounds = await db.SampleRequestSampleTrials.AsNoTracking().OrderBy(x => x.TrialNo).ToArrayAsync();
        Assert.Equal(2, rounds.Length); Assert.Equal(0m, rounds[0].DeliveredSampleQuantityKg); Assert.Equal(100m, rounds[1].DeliveredSampleQuantityKg);
        Assert.All(rounds, t => { Assert.Equal(requestId, t.SampleRequestId); Assert.Equal(formulaId, t.FormulaId); Assert.Null(t.CustomerReplyDate); });
        Assert.Equal(1, await db.SampleRequests.CountAsync());
        Assert.False((await Send(100)).Success);
        Assert.Equal(2, await db.SampleRequestSampleTrials.CountAsync());
        Assert.Equal(1, await ChipThenSampleRules.OptionalChips(db.SampleRequestSampleTrials).CountAsync());
        Assert.Equal(1, await ChipThenSampleRules.PlannedChips(db.SampleRequestSampleTrials, db.SampleRequestWorkflowEvents).CountAsync());
        Assert.Equal(1, await ChipThenSampleRules.BlockingPending(db.SampleRequestSampleTrials).CountAsync());
    }

    private sealed class SaveFailure : Microsoft.EntityFrameworkCore.Diagnostics.SaveChangesInterceptor
    {
        internal string? Error { get; private set; }
        public override Task SaveChangesFailedAsync(Microsoft.EntityFrameworkCore.Diagnostics.DbContextErrorEventData eventData, CancellationToken cancellationToken = default)
        {
            Error = eventData.Exception.ToString();
            return Task.CompletedTask;
        }
    }
}
