public sealed class SampleWorkflowPersistencePostgresTests(IsolatedGroupStoragePostgres postgres)
    : IClassFixture<IsolatedGroupStoragePostgres>
{
    [PostgresGroupStorageFact]
    public async Task WorkflowHandlerPersistsRequestTokenAndQuantityWithEventAtomically()
    {
        await using var connection = await postgres.OpenAsync();
        await using var db = new ApplicationDbContext(new DbContextOptionsBuilder<ApplicationDbContext>().UseNpgsql(connection).Options);
        var names = new[] { "Product", "SampleRequest", "SampleRequestSampleTrial", "Formula", "ProductPricingVersion", "Employee",
            "Customer", "CustomerClaim", "CustomerAssignment",
            "SampleRequestWorkflowEvent", "FormulaVersion", "FormulaVersionItem", "FormulaMaterial", "InternalMessage", "InternalConversation", "OutboxMessage", "AuditLog" };
        foreach (var name in names)
            await CreateTable(connection, db.Model.GetEntityTypes().Single(x => x.ClrType.Name == name));
        // The minimal fixture mirrors the real generated bigint key used when Queue adds an outbox row.
        await using (var identity = new NpgsqlCommand("ALTER TABLE notification.outbox_messages ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY", connection))
            await identity.ExecuteNonQueryAsync();
        var user = new SampleTrialFeedbackCorrectionTests.User("SaleUser");
        var employee = db.Model.GetEntityTypes().Single(x => x.ClrType.Name == "Employee");
        await Insert(connection, employee, new() { ["EmployeeId"] = user.EmployeeId, ["CompanyId"] = user.CompanyId, ["IsActive"] = true });
        foreach (var action in new[] { "PriceRejected", "PriceNoResponse", "RequestSample", "Complete", "Feedback", "FinalizeQuotation", "FinalizeChip" })
        {
            ICurrentUser actor = action is "FinalizeQuotation" or "FinalizeChip" ? new RoleView(user, "LabUser") : user;
            var chipChoice = action is "RequestSample" or "Complete" or "FinalizeChip";
            var customerId = Guid.NewGuid();
            await Insert(connection, db.Model.FindEntityType(typeof(Customer))!, new()
            { ["CustomerId"] = customerId, ["CompanyId"] = user.CompanyId, ["IsActive"] = true, ["IsLead"] = true });
            var requestId = Guid.NewGuid(); var formulaId = Guid.NewGuid(); var productId = Guid.NewGuid(); var trialId = Guid.NewGuid();
            var original = new DateTime(2026, 11, 2, 8, 29, 0).AddTicks(5436160);
            await Insert(connection, db.Model.FindEntityType(typeof(Product))!, new()
            { ["ProductId"] = productId, ["CompanyId"] = user.CompanyId, ["IsActive"] = true });
            await Insert(connection, db.Model.FindEntityType(typeof(SampleRequest))!, new()
            {
                ["SampleRequestId"] = requestId, ["CompanyId"] = user.CompanyId, ["ProductId"] = productId,
                ["CustomerId"] = customerId, ["ManagerBy"] = user.EmployeeId, ["CreatedDate"] = new DateTime(2026, 11, 1), ["UpdatedDate"] = original,
                ["Status"] = action == "Feedback" ? "SampleSent" : "InProgress", ["IsActive"] = true, ["InfoType"] = action == "FinalizeQuotation" ? "Quotation" : "ColorCard", ["FormulaId"] = formulaId,
                ["SampleQuantity"] = chipChoice || action == "FinalizeQuotation" ? 0d : 2d, ["RealPriceQuoteDate"] = original
            });
            await Insert(connection, db.Model.FindEntityType(typeof(Formula))!, new()
            {
                ["FormulaId"] = formulaId, ["CompanyId"] = user.CompanyId, ["ProductId"] = productId,
                ["Status"] = action is "Feedback" or "FinalizeChip" ? "SampleSent" : chipChoice ? "Completed" : "Approved", ["IsActive"] = true, ["UpdatedDate"] = original
            });
            await Insert(connection, db.Model.FindEntityType(typeof(ProductPricingVersion))!, new()
            {
                ["ProductPricingVersionId"] = Guid.NewGuid(), ["CompanyId"] = user.CompanyId, ["ProductId"] = productId,
                ["SourceFormulaId"] = formulaId, ["Currency"] = "VND", ["Status"] = (int)ProductPricingStatus.Approved,
                ["StandardSellingPrice"] = 100m, ["Version"] = 1, ["IsActive"] = true
            });
            if (chipChoice || action == "Feedback")
            {
                await Insert(connection, db.Model.FindEntityType(typeof(SampleRequestSampleTrial))!, new()
                {
                    ["SampleRequestSampleTrialId"] = trialId, ["SampleRequestId"] = requestId, ["FormulaId"] = formulaId,
                    ["Status"] = (int)(action == "Feedback" ? SampleTrialStatus.WaitingCustomerFeedback : SampleTrialStatus.Approved), ["DeliveredSampleQuantityKg"] = 0m,
                    ["SentDate"] = original, ["TrialNo"] = 1, ["IsActive"] = true
                });
            }
            await Insert(connection, db.Model.FindEntityType(typeof(SampleRequestWorkflowEvent))!, new()
            {
                ["Id"] = Guid.NewGuid(), ["SampleRequestId"] = requestId, ["CompanyId"] = user.CompanyId,
                ["RecordedByEmployeeId"] = user.EmployeeId, ["FormulaId"] = formulaId, ["RecordedAt"] = original,
                ["EventType"] = action == "FinalizeChip" ? SampleFlowRules.ChipFinalizationRequested : chipChoice ? SampleFlowRules.ChipFinalized : SampleRequestWorkflowEvents.FormulaConfirmed,
                ["SampleRequestSampleTrialId"] = chipChoice ? trialId : null
            });
            if (chipChoice)
            {
                // Quoted requests require accepted price before finalization/completion.
                await Insert(connection, db.Model.FindEntityType(typeof(SampleRequestWorkflowEvent))!, new()
                {
                    ["Id"] = Guid.NewGuid(), ["SampleRequestId"] = requestId, ["CompanyId"] = user.CompanyId,
                    ["RecordedByEmployeeId"] = user.EmployeeId, ["FormulaId"] = formulaId,
                    ["RecordedAt"] = original.AddSeconds(-1), ["EventType"] = SampleRequestWorkflowEvents.PriceAccepted
                });
            }
            if (action == "FinalizeQuotation")
            {
                await Insert(connection, db.Model.FindEntityType(typeof(SampleRequestWorkflowEvent))!, new()
                {
                    ["Id"] = Guid.NewGuid(), ["SampleRequestId"] = requestId, ["CompanyId"] = user.CompanyId,
                    ["RecordedByEmployeeId"] = user.EmployeeId, ["FormulaId"] = formulaId, ["RecordedAt"] = original.AddSeconds(1),
                    ["EventType"] = SampleRequestWorkflowEvents.PriceAccepted
                });
                // Sale must explicitly ask Lab to finalize after accepting the quotation.
                await Insert(connection, db.Model.FindEntityType(typeof(SampleRequestWorkflowEvent))!, new()
                {
                    ["Id"] = Guid.NewGuid(), ["SampleRequestId"] = requestId, ["CompanyId"] = user.CompanyId,
                    ["RecordedByEmployeeId"] = user.EmployeeId, ["FormulaId"] = formulaId,
                    ["RecordedAt"] = original.AddSeconds(2), ["EventType"] = SampleFlowRules.LabFinalizationRequested
                });
            }
            var handler = new ApplySampleFlowActionCommandHandler(db, actor, new CurrentUserPermissionService(actor),
                RestrictedVisibility.Create(actor), new FormulaVersionService(db, new KeyedMutationLock<Guid>()), null!, db);
            var command = new ApplySampleFlowActionCommand
            {
                SampleRequestId = requestId, Action = action, ExpectedUpdatedDate = original,
                RequestedKg = action == "RequestSample" ? 3d : null,
                ExpectedFormulaUpdatedDate = original,
                Note = "Actual handler regression", PriceReference = "UAT-PRICE",
                CustomerFeedbackNote = action is "PriceRejected" or "PriceNoResponse" ? "Shared customer feedback" : null
            };
            if (action == "FinalizeQuotation")
            {
                var saleHandler = new ApplySampleFlowActionCommandHandler(db, user, new CurrentUserPermissionService(user),
                    RestrictedVisibility.Create(user), new FormulaVersionService(db, new KeyedMutationLock<Guid>()), null!, db);
                Assert.False((await saleHandler.Handle(command, default)).Success);
                Assert.False((await saleHandler.Handle(new() { SampleRequestId = requestId, Action = "Complete",
                    ExpectedUpdatedDate = original, ExpectedFormulaUpdatedDate = original }, default)).Success);
            }
            var result = action == "Feedback"
                ? await new RecordSampleRequestSampleTrialCustomerFeedbackCommandHandler(db, user, RestrictedVisibility.Create(user),
                    new Clock(), null!, new CurrentUserPermissionService(user)).Handle(new RecordSampleRequestSampleTrialCustomerFeedbackCommand
                    {
                        SampleRequestId = requestId, Status = SampleTrialStatus.Failed,
                        CustomerReplyStatus = "Không đạt", CustomerReplyNote = "Restricted Sale real handler regression"
                    }, default)
                : await handler.Handle(command, default);
            Assert.True(result.Success, $"{action}: {result.Message}");
            // Re-read from the database rather than using the mutated handler object/change tracker.
            var saved = await db.SampleRequests.AsNoTracking().SingleAsync(x => x.SampleRequestId == requestId);
            Assert.True(saved.UpdatedDate > original, $"{action} did not persist its request token");
            Assert.Equal(user.EmployeeId, saved.UpdatedBy);
            Assert.Equal(action == "RequestSample" ? 3d : chipChoice || action == "FinalizeQuotation" ? 0d : 2d, saved.SampleQuantity);
            if (action == "Complete")
            {
                Assert.Equal("Completed", saved.Status);
                var selected = await db.Formulas.AsNoTracking().SingleAsync(x => x.FormulaId == formulaId);
                Assert.True(selected.IsSelect);
                Assert.True(selected.UpdatedDate > original);
            }
            if (action == "FinalizeChip")
            {
                var finalized = await db.Formulas.AsNoTracking().SingleAsync(x => x.FormulaId == formulaId);
                Assert.Equal("Completed", finalized.Status);
                Assert.True(finalized.IsSelect);
                Assert.Equal("Completed", saved.Status);
                Assert.Equal(formulaId, saved.FormulaId);
            }
            if (action == "Feedback")
            {
                Assert.Equal("InProgress", saved.Status);
                Assert.Equal("Rework", (await db.Formulas.AsNoTracking().SingleAsync(x => x.FormulaId == formulaId)).Status);
                Assert.Equal(SampleTrialStatus.Failed, (await db.SampleRequestSampleTrials.AsNoTracking().SingleAsync(x => x.SampleRequestId == requestId)).Status);
            }
            if (action == "FinalizeQuotation")
            {
                Assert.Equal("Completed", saved.Status);
                Assert.Equal(formulaId, saved.FormulaId);
                var finalized = await db.Formulas.AsNoTracking().SingleAsync(x => x.FormulaId == formulaId);
                Assert.Equal("Completed", finalized.Status);
                Assert.True(finalized.IsSelect);
                var orderService = new SaleOrderCreationService(db, null!, null!, null!, null!, HRM.Application.Tests.Features.CRM.CustomerCare.CustomerSampleSharingTestServices.Disabled());
                Assert.DoesNotContain(formulaId, await orderService.LoadUnfinishedWorkflowFormulaIdsAsync(user.CompanyId!.Value, [formulaId], default));
                Assert.Single(await db.FormulaVersions.AsNoTracking().Where(x => x.FormulaId == formulaId).ToArrayAsync());
            }
            var eventType = action == "FinalizeChip" ? SampleFlowRules.ChipFinalized : action == "FinalizeQuotation" ? SampleFlowRules.QuotationFinalized : action == "Feedback" ? SampleRequestWorkflowEvents.FeedbackRecorded : action == "Complete" ? SampleFlowRules.CompletedWithoutTrial : action == "RequestSample" ? SampleFlowRules.KgRequested : action == "PriceRejected" ? SampleFlowRules.PriceRejected : SampleFlowRules.PriceNoResponse;
            Assert.Equal(1, await db.SampleRequestWorkflowEvents.CountAsync(x => x.SampleRequestId == requestId && x.EventType == eventType));
            if (action is "PriceRejected" or "PriceNoResponse")
            {
                var primary = await db.SampleRequestWorkflowEvents.AsNoTracking().SingleAsync(x => x.SampleRequestId == requestId && x.EventType == eventType);
                var shared = await db.SampleRequestWorkflowEvents.AsNoTracking().SingleAsync(x => x.RelatedEventId == primary.Id && x.EventType == SampleFlowRules.PriceFeedbackShared);
                Assert.Equal(command.CustomerFeedbackNote, shared.Note);
                Assert.Equal(command.Note, primary.Note);
                Assert.Null(shared.PriceReference);
            }
            var outboxCount = await db.OutboxMessages.CountAsync();
            var replay = action == "Feedback"
                ? await new RecordSampleRequestSampleTrialCustomerFeedbackCommandHandler(db, user, RestrictedVisibility.Create(user),
                    new Clock(), null!, new CurrentUserPermissionService(user)).Handle(new RecordSampleRequestSampleTrialCustomerFeedbackCommand
                    {
                        SampleRequestId = requestId, Status = SampleTrialStatus.Failed, CustomerReplyStatus = "Không đạt"
                    }, default)
                : await handler.Handle(command, default);
            Assert.False(replay.Success); // stale token or already answered round cannot append duplicate work
            Assert.Equal(outboxCount, await db.OutboxMessages.CountAsync());
            if (action == "RequestSample")
            {
                // A later kg delivery was rejected. Requesting another run must not create another TP.
                await db.SampleRequestSampleTrials.Where(x => x.SampleRequestSampleTrialId == trialId)
                    .ExecuteUpdateAsync(set => set.SetProperty(x => x.DeliveredSampleQuantityKg, 2m)
                        .SetProperty(x => x.Status, SampleTrialStatus.Failed)
                        .SetProperty(x => x.CustomerReplyNote, "Original rejection"));
                await db.Formulas.Where(x => x.FormulaId == formulaId)
                    .ExecuteUpdateAsync(set => set.SetProperty(x => x.Status, "SampleSent"));
                db.ChangeTracker.Clear();
                var before = await db.SampleRequests.AsNoTracking().SingleAsync(x => x.SampleRequestId == requestId);
                var count = await db.SampleRequests.CountAsync();
                var jobs = await db.OutboxMessages.CountAsync();
                var again = await handler.Handle(new() { SampleRequestId = requestId, Action = "RequestSample",
                    RequestedKg = 7, ExpectedUpdatedDate = before.UpdatedDate, Note = "Run another VU" }, default);
                Assert.True(again.Success, again.Message);
                Assert.Equal(requestId, again.Data);
                Assert.Equal(count, await db.SampleRequests.CountAsync());
                Assert.Equal(jobs + 1, await db.OutboxMessages.CountAsync());
                var next = await db.SampleRequests.AsNoTracking().SingleAsync(x => x.SampleRequestId == requestId);
                Assert.Equal(productId, next.ProductId);
                Assert.Equal(7, next.SampleQuantity);
                var old = await db.SampleRequestSampleTrials.AsNoTracking().SingleAsync(x => x.SampleRequestSampleTrialId == trialId);
                Assert.Equal(formulaId, old.FormulaId);
                Assert.Equal(original, old.SentDate);
                Assert.Equal("Original rejection", old.CustomerReplyNote);
                Assert.Equal(SampleTrialStatus.Failed, old.Status);
                Assert.Equal("SampleSent", (await db.Formulas.AsNoTracking().SingleAsync(x => x.FormulaId == formulaId)).Status);
            }
            if (action == "FinalizeQuotation")
            {
                var finalized = await db.Formulas.AsNoTracking().SingleAsync(x => x.FormulaId == formulaId);
                var saleHandler = new ApplySampleFlowActionCommandHandler(db, user, new CurrentUserPermissionService(user),
                    RestrictedVisibility.Create(user), new FormulaVersionService(db, new KeyedMutationLock<Guid>()), null!, db);
                db.ChangeTracker.Clear(); // A subsequent HTTP request re-reads DB timestamps at PostgreSQL precision.
                var completed = await saleHandler.Handle(new() { SampleRequestId = requestId, Action = "Complete",
                    ExpectedUpdatedDate = saved.UpdatedDate, ExpectedFormulaUpdatedDate = finalized.UpdatedDate }, default);
                Assert.False(completed.Success); // Lab already completed this request; no second Sale confirmation.
                Assert.Equal("Completed", (await db.SampleRequests.AsNoTracking().SingleAsync(x => x.SampleRequestId == requestId)).Status);
                Assert.True((await db.Formulas.AsNoTracking().SingleAsync(x => x.FormulaId == formulaId)).IsSelect);
                // A completed ordinary request accepts only an explicit public note, without reopening its lifecycle.
                var beforeNote = await db.SampleRequests.AsNoTracking().SingleAsync(x => x.SampleRequestId == requestId);
                var latestPrice = await db.SampleRequestWorkflowEvents.AsNoTracking().Where(x => x.SampleRequestId == requestId &&
                    x.EventType == SampleRequestWorkflowEvents.PriceAccepted).SingleAsync();
                var publicNoteHandler = new RecordCustomerFeedbackNoteCommandHandler(db, user, new CurrentUserPermissionService(user),
                    RestrictedVisibility.Create(user));
                var publicNoteCommand = new RecordCustomerFeedbackNoteCommand
                { SampleRequestId = requestId, ExpectedRequestUpdatedDate = beforeNote.UpdatedDate,
                    ExpectedPriceEventId = latestPrice.Id, CustomerFeedbackNote = "Explicit shared feedback after completion" };
                var beforeJobs = await db.OutboxMessages.CountAsync();
                var publicNoteResult = await publicNoteHandler.Handle(publicNoteCommand, default);
                Assert.True(publicNoteResult.Success, publicNoteResult.Message);
                var afterNote = await db.SampleRequests.AsNoTracking().SingleAsync(x => x.SampleRequestId == requestId);
                Assert.Equal("Completed", afterNote.Status);
                Assert.True(afterNote.UpdatedDate > beforeNote.UpdatedDate);
                Assert.True((await db.Formulas.AsNoTracking().SingleAsync(x => x.FormulaId == formulaId)).IsSelect);
                Assert.Equal(beforeJobs + 1, await db.OutboxMessages.CountAsync());
                var publicEvent = await db.SampleRequestWorkflowEvents.AsNoTracking().Where(x => x.RelatedEventId == latestPrice.Id &&
                    x.EventType == SampleFlowRules.PriceFeedbackShared).SingleAsync();
                Assert.Equal(publicNoteCommand.CustomerFeedbackNote, publicEvent.Note);
                Assert.Null(publicEvent.PriceReference);
                Assert.False((await publicNoteHandler.Handle(publicNoteCommand, default)).Success);
                var labUser = new RoleView(user, "LabUser");
                Assert.False((await new RecordCustomerFeedbackNoteCommandHandler(db, labUser, new CurrentUserPermissionService(labUser),
                    RestrictedVisibility.Create(labUser)).Handle(publicNoteCommand, default)).Success);
                var outsider = new RoleView(user, "SaleUser", Guid.NewGuid());
                await Insert(connection, employee, new() { ["EmployeeId"] = outsider.EmployeeId, ["CompanyId"] = user.CompanyId, ["IsActive"] = true });
                Assert.False((await new RecordCustomerFeedbackNoteCommandHandler(db, outsider, new CurrentUserPermissionService(outsider),
                    RestrictedVisibility.Create(outsider)).Handle(publicNoteCommand, default)).Success);

                publicNoteCommand.ExpectedRequestUpdatedDate = afterNote.UpdatedDate;
                Assert.True((await publicNoteHandler.Handle(publicNoteCommand, default)).Success);
                Assert.Equal(beforeJobs + 1, await db.OutboxMessages.CountAsync());
                publicNoteCommand.ExpectedPriceEventId = Guid.NewGuid();
                Assert.False((await publicNoteHandler.Handle(publicNoteCommand, default)).Success);
                publicNoteCommand.ExpectedPriceEventId = latestPrice.Id;
                publicNoteCommand.CustomerFeedbackNote = new string('x', 2001);
                Assert.False((await publicNoteHandler.Handle(publicNoteCommand, default)).Success);
                publicNoteCommand.CustomerFeedbackNote = "New public note";
                await db.SampleRequests.Where(x => x.SampleRequestId == requestId).ExecuteUpdateAsync(set => set.SetProperty(x => x.Status, "Cancelled"));
                Assert.False((await publicNoteHandler.Handle(publicNoteCommand, default)).Success);
                Assert.Equal(beforeJobs + 1, await db.OutboxMessages.CountAsync());


                Assert.Empty(await new SaleOrderCreationService(db, null!, null!, null!, null!, HRM.Application.Tests.Features.CRM.CustomerCare.CustomerSampleSharingTestServices.Disabled())
                    .LoadUnfinishedWorkflowFormulaIdsAsync(user.CompanyId!.Value, [formulaId], default));
            }
        }
    }
    private sealed class RoleView(ICurrentUser source, string role, Guid? employeeOverride = null) : ICurrentUser
    {
        public bool IsAuthenticated => source.IsAuthenticated;
        public Guid UserId => source.UserId;
        public Guid? EmployeeId => employeeOverride ?? source.EmployeeId;
        public Guid? CompanyId => source.CompanyId;
        public string? UserName => source.UserName;
        public string? Email => source.Email;
        public IReadOnlyCollection<string> Roles => [role];
        public bool IsInRole(string value) => value == role;
    }
    private sealed class Clock : IDateTimeProvider { public DateTime Now => DateTime.Now; }

    public class RestrictedVisibility : DispatchProxy
    {
        private ICurrentUser _user = null!;
        public static ICustomerVisibilityService Create(ICurrentUser user)
        {
            var service = Create<ICustomerVisibilityService, RestrictedVisibility>();
            ((RestrictedVisibility)service)._user = user;
            return service;
        }
        protected override object? Invoke(MethodInfo? method, object?[]? args) => method!.Name switch
        {
            "BuildScopeAsync" or "BuildReadScopeAsync" => Task.FromResult(new ViewerScope(_user.CompanyId!.Value,
                _user.EmployeeId!.Value, false, false, new HashSet<Guid>(), new HashSet<Guid>(), DateTime.Now)),
            // Use the real visibility expression, including its nested no-tracking customer query.
            "ApplySampleRequestVisibility" => new CustomerVisibilityService(null!, null!, null!).ApplySampleRequestVisibility(
                (IQueryable<SampleRequest>)args![0]!, (IQueryable<Customer>)args[1]!, (ViewerScope)args[2]!),
            _ => throw new NotSupportedException(method.Name)
        };
    }

