namespace HRM.Application.Tests.Features.PLM.SampleRequests;

public static class SampleWorkflowMutationTestSupport
{
    internal static async Task Schema(NpgsqlConnection connection, ApplicationDbContext db)
    {
        foreach (var name in new[] { "SampleRequest", "SampleRequestSampleTrial", "SampleRequestWorkflowEvent", "Formula", "Product", "Customer", "Employee",
            "Category", "FormulaVersion", "FormulaVersionItem", "FormulaMaterial", "ProductPricingVersion", "InternalMessage", "InternalConversation", "OutboxMessage", "AuditLog",
            "CustomerInteraction", "CustomerInteractionReference" })
            await SampleDeliveryOptionsPostgresTests.CreateTable(connection, db.Model.GetEntityTypes().Single(e => e.ClrType.Name == name));
        await using var identity = new NpgsqlCommand("ALTER TABLE notification.outbox_messages ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY", connection);
        await identity.ExecuteNonQueryAsync();
    }

    internal sealed class Actor(Guid company, Guid employee, string role) : ICurrentUser
    {
        public bool IsAuthenticated => true;
        public Guid UserId { get; } = Guid.NewGuid();
        public Guid? CompanyId => company;
        public Guid? EmployeeId => employee;
        public string? UserName => "isolated-workflow-test";
        public string? Email => null;
        public IReadOnlyCollection<string> Roles => [role];
        public bool IsInRole(string candidate) => role == candidate;
    }

    public class Visibility : DispatchProxy
    {
        private ICurrentUser _actor = null!;
        private bool _visible;
        internal static ICustomerVisibilityService Create(ICurrentUser actor, bool visible = true)
        {
            var proxy = Create<ICustomerVisibilityService, Visibility>();
            ((Visibility)proxy)._actor = actor;
            ((Visibility)proxy)._visible = visible;
            return proxy;
        }
        protected override object? Invoke(MethodInfo? method, object?[]? args)
            => method!.Name switch {
                "BuildScopeAsync" or "BuildReadScopeAsync" => Task.FromResult(new ViewerScope(_actor.CompanyId!.Value,
                    _actor.EmployeeId!.Value, true, false, new HashSet<Guid>(), new HashSet<Guid>(), DateTime.Now)),
                "ApplySampleRequestVisibility" => _visible ? args![0] : ((IQueryable<SampleRequest>)args![0]!).Where(_ => false),
                "ApplyCustomerVisibility" => args![0],
                _ => throw new NotSupportedException(method.Name)
            };
    }

    public class FeedbackSender : DispatchProxy
    {
        private RecordSampleOptionFeedbackCommandHandler _handler = null!;
        internal static ISender Create(RecordSampleOptionFeedbackCommandHandler handler)
        {
            var proxy = Create<ISender, FeedbackSender>();
            ((FeedbackSender)proxy)._handler = handler;
            return proxy;
        }
        protected override object? Invoke(MethodInfo? method, object?[]? args)
            => method?.Name == "Send" && args?[0] is RecordSampleOptionFeedbackCommand command
                ? _handler.Handle(command, args.Length > 1 && args[1] is CancellationToken ct ? ct : default)
                : throw new NotSupportedException(method?.Name);
    }
}
