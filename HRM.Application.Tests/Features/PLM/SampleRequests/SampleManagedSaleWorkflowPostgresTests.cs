public sealed class SampleManagedSaleWorkflowPostgresTests(IsolatedGroupStoragePostgres postgres) : IClassFixture<IsolatedGroupStoragePostgres>
{
    [PostgresGroupStorageFact]
    public async Task SaleAdminDelegationRequiresManagedOwnerEvenWithFullReadViewAndKeepsActualActor()
    {
        await using var connection = await postgres.OpenAsync();
        await using var db = new ApplicationDbContext(new DbContextOptionsBuilder<ApplicationDbContext>().UseNpgsql(connection).Options);
        foreach (var name in new[] { "SampleRequest", "SampleRequestSampleTrial", "Formula", "ProductPricingVersion", "Employee", "Customer",
            "Product", "CustomerInteraction", "CustomerInteractionReference", "SampleRequestWorkflowEvent", "FormulaVersion", "InternalMessage", "InternalConversation", "OutboxMessage", "AuditLog" })
            await CreateTable(connection, db.Model.GetEntityTypes().Single(x => x.ClrType.Name == name));
        await using (var identity = new NpgsqlCommand("ALTER TABLE notification.outbox_messages ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY", connection))
            await identity.ExecuteNonQueryAsync();
        await using (var defaults = new NpgsqlCommand("ALTER TABLE \"Customer\".\"CustomerInteractions\" ALTER COLUMN \"IsActive\" SET DEFAULT TRUE", connection))
            await defaults.ExecuteNonQueryAsync();
        var company = Guid.NewGuid(); var actorId = Guid.NewGuid(); var ownerId = Guid.NewGuid();
        var employee = db.Model.GetEntityTypes().Single(x => x.ClrType.Name == "Employee");
        await Insert(connection, employee, new() { ["EmployeeId"] = actorId, ["CompanyId"] = company, ["IsActive"] = true });
        await Insert(connection, employee, new() { ["EmployeeId"] = ownerId, ["CompanyId"] = company, ["IsActive"] = true });
        var actor = new Actor(company, actorId);
        foreach (var scenario in new[] { "managed", "outside-group-fullview", "foreign-company", "managed-cap-revoked" })
        {
            var id = Guid.NewGuid(); var formula = Guid.NewGuid(); var product = Guid.NewGuid(); var customer = Guid.NewGuid();
            var original = new DateTime(2026, 11, 2, 8, 0, 0);
            var scopedCompany = scenario == "foreign-company" ? Guid.NewGuid() : company;
            await Insert(connection, db.Model.FindEntityType(typeof(Customer))!, new()
            { ["CustomerId"] = customer, ["CompanyId"] = scopedCompany, ["IsActive"] = true, ["IsLead"] = true, ["CurrentSaleId"] = ownerId });
            await Insert(connection, db.Model.FindEntityType(typeof(SampleRequest))!, new()
            { ["SampleRequestId"] = id, ["CompanyId"] = scopedCompany, ["CustomerId"] = customer, ["ProductId"] = product,
              ["ManagerBy"] = ownerId, ["CreatedDate"] = original, ["UpdatedDate"] = original, ["IsActive"] = true,
              ["InfoType"] = "ColorCard", ["SampleQuantity"] = 2d, ["FormulaId"] = formula, ["Status"] = "InProgress", ["RealPriceQuoteDate"] = original });
            await Insert(connection, db.Model.FindEntityType(typeof(Product))!, new()
            { ["ProductId"] = product, ["CompanyId"] = scopedCompany, ["IsActive"] = true });
            await Insert(connection, db.Model.FindEntityType(typeof(Formula))!, new()
            { ["FormulaId"] = formula, ["ProductId"] = product, ["CompanyId"] = scopedCompany, ["IsActive"] = true, ["Status"] = "Approved" });
            await Insert(connection, db.Model.FindEntityType(typeof(ProductPricingVersion))!, new()
            { ["ProductPricingVersionId"] = Guid.NewGuid(), ["ProductId"] = product, ["CompanyId"] = scopedCompany,
              ["SourceFormulaId"] = formula, ["Status"] = (int)ProductPricingStatus.Approved, ["StandardSellingPrice"] = 100m,
              ["Version"] = 1, ["Currency"] = "VND", ["IsActive"] = true });
            await Insert(connection, db.Model.FindEntityType(typeof(SampleRequestWorkflowEvent))!, new()
            { ["Id"] = Guid.NewGuid(), ["SampleRequestId"] = id, ["CompanyId"] = scopedCompany,
              ["FormulaId"] = formula, ["RecordedAt"] = original, ["EventType"] = SampleRequestWorkflowEvents.FormulaConfirmed });
            ICurrentUser effective = scenario == "managed-cap-revoked" ? new Actor(company, actorId, true) : actor;
            var scope = new ViewerScope(company, actorId, true, false, new HashSet<Guid>(),
                scenario == "outside-group-fullview" ? new HashSet<Guid>() : new HashSet<Guid> { ownerId }, DateTime.Now);
            var visibility = ScopedVisibility.Create(scope);
            var permissions = new CurrentUserPermissionService(effective);
            var handler = new ApplySampleFlowActionCommandHandler(db, effective, permissions, visibility, null!, null!, db);
            var jobsBefore = await db.OutboxMessages.CountAsync();
            var result = await handler.Handle(new() { SampleRequestId = id, Action = "PriceNoResponse", ExpectedUpdatedDate = original,
                PriceReference = "Private reference", CustomerFeedbackNote = "Shared actual customer feedback" }, default);
            var crmTrial = Guid.NewGuid();
            await Insert(connection, db.Model.FindEntityType(typeof(SampleRequestSampleTrial))!, new()
            { ["SampleRequestSampleTrialId"] = crmTrial, ["SampleRequestId"] = id, ["FormulaId"] = formula,
              ["IsActive"] = true, ["TrialNo"] = 1, ["DeliveredSampleQuantityKg"] = 0m,
              ["Status"] = (int)SampleTrialStatus.WaitingCustomerFeedback, ["SentDate"] = original, ["UpdatedDate"] = original });
            var crmHandler = new CreateSampleTrialInteractionCommandHandler(db, db, new CustomerCrmAccessService(db, visibility),
                new Clock(), null!, effective, permissions);
            var crmCommand = new CreateSampleTrialInteractionCommand { Request = new()
            { CustomerId = customer, SampleRequestSampleTrialId = crmTrial, IdempotencyKey = Guid.NewGuid(),
              Content = "Managed Sale customer feedback", CustomerReplyStatus = "FAIL", ExpectedTrialUpdatedDate = original } };
            if (scenario != "managed")
            {
                Assert.False(result.Success, scenario);
                Assert.False((await crmHandler.Handle(crmCommand, default)).Success, "Direct CRM endpoint must not bypass the managed-owner gate.");
                Assert.Equal(jobsBefore, await db.OutboxMessages.CountAsync());
                Assert.Equal(original, (await db.SampleRequests.AsNoTracking().SingleAsync(x => x.SampleRequestId == id)).UpdatedDate);
                continue;
            }
            Assert.True(result.Success, result.Message);
            var saved = await db.SampleRequests.AsNoTracking().SingleAsync(x => x.SampleRequestId == id);
            Assert.Equal(ownerId, saved.ManagerBy); Assert.Equal(actorId, saved.UpdatedBy);
            var primary = await db.SampleRequestWorkflowEvents.AsNoTracking().SingleAsync(x => x.SampleRequestId == id && x.EventType == SampleFlowRules.PriceNoResponse);
            Assert.Equal(actorId, primary.RecordedByEmployeeId);
            Assert.Equal(2, await db.OutboxMessages.CountAsync() - jobsBefore);
            var publicHandler = new RecordCustomerFeedbackNoteCommandHandler(db, effective, permissions, visibility);
            var publicResult = await publicHandler.Handle(new() { SampleRequestId = id, ExpectedPriceEventId = primary.Id,
                ExpectedRequestUpdatedDate = saved.UpdatedDate, CustomerFeedbackNote = "Managed Sale note revision" }, default);
            Assert.True(publicResult.Success, publicResult.Message);
            saved = await db.SampleRequests.AsNoTracking().SingleAsync(x => x.SampleRequestId == id);
            db.ChangeTracker.Clear(); // Simulate the subsequent CRM HTTP request with fresh concurrency snapshots.
            var crmResult = await crmHandler.Handle(crmCommand, default);
            Assert.True(crmResult.Success, crmResult.Message);
            var interaction = await db.CustomerInteractions.AsNoTracking().SingleAsync(x => x.Id == crmResult.Data);
            Assert.Equal(actorId, interaction.CreatedBy);
            Assert.Equal(ownerId, interaction.AssignedSaleEmployeeId);
            Assert.Equal(ownerId, (await db.Customers.AsNoTracking().SingleAsync(x => x.CustomerId == customer)).CurrentSaleId);
            Assert.NotNull((await db.Customers.AsNoTracking().SingleAsync(x => x.CustomerId == customer)).LastContactDate);

            Assert.Equal(ownerId, (await db.SampleRequests.AsNoTracking().SingleAsync(x => x.SampleRequestId == id)).ManagerBy);

            saved = await db.SampleRequests.AsNoTracking().SingleAsync(x => x.SampleRequestId == id);
            db.ChangeTracker.Clear();
            var trial = Guid.NewGuid(); var trialDate = original.AddDays(1);
            await Insert(connection, db.Model.FindEntityType(typeof(SampleRequestSampleTrial))!, new()
            { ["SampleRequestSampleTrialId"] = trial, ["SampleRequestId"] = id, ["FormulaId"] = formula, ["IsActive"] = true,
              ["TrialNo"] = 2, ["Status"] = (int)SampleTrialStatus.Approved, ["SentDate"] = original, ["CustomerReplyDate"] = trialDate,
              ["CustomerReplyNote"] = "Before", ["UpdatedDate"] = trialDate });
            var correction = await new CorrectSampleTrialFeedbackCommandHandler(db, effective, permissions, visibility, new Clock()).Handle(new()
            { SampleRequestId = id, TrialId = trial, ExpectedRequestUpdatedDate = saved.UpdatedDate, ExpectedTrialUpdatedDate = trialDate,
              CustomerReplyDate = trialDate, CustomerReplyNote = "Managed Sale correction" }, default);
            Assert.True(correction.Success, correction.Message);
            Assert.Equal(actorId, (await db.SampleRequestSampleTrials.AsNoTracking().SingleAsync(x => x.SampleRequestSampleTrialId == trial)).UpdatedBy);
            var explicitTrial = Guid.NewGuid();
            await Insert(connection, db.Model.FindEntityType(typeof(SampleRequestSampleTrial))!, new()
            { ["SampleRequestSampleTrialId"] = explicitTrial, ["SampleRequestId"] = id, ["FormulaId"] = formula,
              ["IsActive"] = true, ["TrialNo"] = 3, ["DeliveredSampleQuantityKg"] = 0m,
              ["Status"] = (int)SampleTrialStatus.WaitingCustomerFeedback, ["SentDate"] = original, ["UpdatedDate"] = original });
            db.ChangeTracker.Clear();
            var explicitResult = await crmHandler.Handle(new() { Request = new()
            { CustomerId = customer, SampleRequestSampleTrialId = explicitTrial, IdempotencyKey = Guid.NewGuid(),
              Content = "Explicit interaction assignee", CustomerReplyStatus = "FAIL", ExpectedTrialUpdatedDate = original,
              AssignedSaleEmployeeId = actorId } }, default);
            Assert.True(explicitResult.Success, explicitResult.Message);
            Assert.Equal(actorId, (await db.CustomerInteractions.AsNoTracking().SingleAsync(x => x.Id == explicitResult.Data)).CreatedBy);
            Assert.Equal(ownerId, (await db.Customers.AsNoTracking().SingleAsync(x => x.CustomerId == customer)).CurrentSaleId);

            Assert.Equal(ownerId, (await db.SampleRequests.AsNoTracking().SingleAsync(x => x.SampleRequestId == id)).ManagerBy);

        }
    }
    private sealed class Clock : HRM.Application.Abstractions.Commons.Time.IDateTimeProvider { public DateTime Now => DateTime.Now; }
    private sealed class Actor(Guid company, Guid employee, bool revokeManaged = false) : ICurrentUser
    {
        public bool IsAuthenticated => true; public Guid UserId { get; } = Guid.NewGuid(); public Guid? CompanyId => company;
        public Guid? EmployeeId => employee; public string? UserName => null; public string? Email => null;
        public IReadOnlyCollection<string> Roles => ["SaleAdmin"]; public bool IsInRole(string role) => role == "SaleAdmin";
        public bool HasExplicitPermissionSet => revokeManaged;
        public IReadOnlyCollection<string> Permissions => revokeManaged ? [ApplicationPermissions.PLM.ManageSampleSaleWorkflow,
            ApplicationPermissions.PLM.CorrectSampleTrialFeedback, ApplicationPermissions.PLM.ConfirmCustomerPrice] : [];
    }
    public class ScopedVisibility : DispatchProxy
    {
        private ViewerScope _scope = null!;
        internal static ICustomerVisibilityService Create(ViewerScope scope)
        { var result = Create<ICustomerVisibilityService, ScopedVisibility>(); ((ScopedVisibility)result)._scope = scope; return result; }
        protected override object? Invoke(MethodInfo? method, object?[]? args) => method!.Name switch
        {
            "BuildScopeAsync" or "BuildReadScopeAsync" => Task.FromResult(_scope),
            "ApplyCustomerVisibility" => new CustomerVisibilityService(null!, null!, null!).ApplyCustomerVisibility(
                (IQueryable<Customer>)args![0]!, (ViewerScope)args[1]!),
            "ApplySampleRequestVisibility" => new CustomerVisibilityService(null!, null!, null!).ApplySampleRequestVisibility(
                (IQueryable<SampleRequest>)args![0]!, (IQueryable<Customer>)args[1]!, (ViewerScope)args[2]!),
            _ => throw new NotSupportedException(method.Name)
        };
    }
}
