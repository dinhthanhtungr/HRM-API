public sealed class SampleDeliveryOptionsPostgresTests(IsolatedGroupStoragePostgres postgres) : IClassFixture<IsolatedGroupStoragePostgres>
{
    [PostgresGroupStorageFact]
    public async Task FeedbackIsAtomicScopedIdempotentAndAllowsCorrectingNonLatestOption()
    {
        await using var connection = await postgres.OpenAsync();
        await using var db = new ApplicationDbContext(new DbContextOptionsBuilder<ApplicationDbContext>().UseNpgsql(connection).Options);
        foreach (var type in new[] { typeof(SampleRequest), typeof(SampleRequestSampleTrial), typeof(SampleRequestWorkflowEvent), typeof(Formula),
            typeof(Product), typeof(Customer), typeof(Employee), typeof(AuditLog), typeof(OutboxMessage), typeof(CustomerInteraction), typeof(CustomerInteractionReference), typeof(FormulaVersion) })
            await CreateTable(connection, db.Model.FindEntityType(type)!);
        await using (var identity = new NpgsqlCommand("ALTER TABLE notification.outbox_messages ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY", connection))
            await identity.ExecuteNonQueryAsync();
        var user = new SampleTrialFeedbackCorrectionTests.User("SaleUser"); var company = user.CompanyId!.Value; var employee = user.EmployeeId!.Value;
        var date = new DateTime(2026,11,14,8,0,0); var parent = new SampleRequest { SampleRequestId = Guid.NewGuid(), CompanyId = company,
            ManagerBy = employee, Status = "SampleSent", CreatedDate = date, UpdatedDate = date, SampleQuantity = 2, IsActive = true, ExternalId = "TP_TEST",
            CustomerId = Guid.NewGuid(), ProductId = Guid.NewGuid() };
        db.Customers.Add(new Customer { CustomerId = parent.CustomerId, CompanyId = company, CustomerName = "Test", IsActive = true });
        db.Products.Add(new Product { ProductId = parent.ProductId, CompanyId = company, IsActive = true, Name = "Sample" });
        db.Employees.Add(new Employee { EmployeeId = employee, CompanyId = company, IsActive = true });
        db.SampleRequests.Add(parent);
        var trials = SampleDeliveryOptionsTests.Trials();
        foreach (var trial in trials)
        {
            trial.SampleRequestId = parent.SampleRequestId; trial.CreatedDate = date; trial.UpdatedDate = date;
            db.Formulas.Add(new Formula { FormulaId = trial.FormulaId!.Value, ProductId = parent.ProductId, CompanyId = company,
                IsActive = true, Status = "SampleSent", ExternalId = "VU_TEST_" + trial.TrialNo, UpdatedDate = date });
        }
        db.SampleRequestSampleTrials.AddRange(trials);
        var events = SampleDeliveryOptionsTests.Events(trials);
        foreach (var evt in events) { evt.CompanyId = company; evt.SampleRequestId = parent.SampleRequestId; evt.RecordedAt = date; evt.OccurredAt = date; }
        db.SampleRequestWorkflowEvents.AddRange(events);
        await db.SaveChangesAsync(); db.ChangeTracker.Clear();
        var visibility = SampleTrialFeedbackCorrectionTests.Visibility.Create(user); var permissions = new CurrentUserPermissionService(user);
        var handler = new RecordSampleOptionFeedbackCommandHandler(db, user, permissions, visibility, new Clock(), db, new(db));
        var batchId = events.Single(e => e.EventType == SampleDeliveryRules.BatchSent).Id;
        var command = new RecordSampleOptionFeedbackCommand { SampleRequestId = parent.SampleRequestId, BatchId = batchId, TrialId = trials[0].SampleRequestSampleTrialId,
            OperationId = Guid.NewGuid(), Approved = true, ReplyDate = new(2026,11,16), Note = "Selected first option", ExpectedRequestUpdatedDate = date, ExpectedTrialUpdatedDate = date };
        var saved = await handler.Handle(command, default); Assert.True(saved.Success, saved.Message);
        db.ChangeTracker.Clear();
        var stored = await db.SampleRequestSampleTrials.OrderBy(t => t.TrialNo).ToArrayAsync();
        Assert.Equal("APPROVED", stored[0].CustomerReplyStatus); Assert.All(stored.Skip(1), t => Assert.Equal("FAIL", t.CustomerReplyStatus));
        Assert.Single(await db.CustomerInteractions.ToListAsync()); Assert.Single(await db.OutboxMessages.ToListAsync());
        Assert.True((await handler.Handle(command, default)).Success);
        Assert.Equal(1, await db.CustomerInteractions.CountAsync());
        var read = await new GetSampleDeliveriesQueryHandler(db, user, permissions, visibility).Handle(new(parent.SampleRequestId), default);
        Assert.False(read!.Batches.Single().CanCorrect);
        var completedRequest = await db.SampleRequests.SingleAsync();
        Assert.Equal("Completed", completedRequest.Status);
        Assert.Equal(trials[0].FormulaId, completedRequest.FormulaId);
        Assert.Equal("Completed", (await db.Formulas.SingleAsync(f => f.FormulaId == trials[0].FormulaId)).Status);
        Assert.Equal(trials[0].FormulaId, (await db.Formulas.SingleAsync(f => f.IsSelect)).FormulaId);
        Assert.Equal(3, read.Batches.Single().Options.Count);
        var active = db.SampleRequestSampleTrials.Where(t => t.IsActive);
        var latest = active.Where(t => !active.Any(n => n.SampleRequestId == t.SampleRequestId && n.TrialNo > t.TrialNo));
        Assert.Equal(stored[0].SampleRequestSampleTrialId, await SampleDeliveryRules.Representatives(latest, active, db.SampleRequestWorkflowEvents).Select(t => t.SampleRequestSampleTrialId).SingleAsync());
        // Stale parent token must roll back all sibling changes.
        command.OperationId = Guid.NewGuid(); command.TrialId = trials[2].SampleRequestSampleTrialId;
        Assert.False((await handler.Handle(command, default)).Success);
        db.ChangeTracker.Clear(); Assert.Equal("APPROVED", await db.SampleRequestSampleTrials.Where(t => t.TrialNo == 1).Select(t => t.CustomerReplyStatus).SingleAsync());
        // Auto-completion closes result editing; a correction cannot silently reopen it.
        command.ExpectedRequestUpdatedDate = (await db.SampleRequests.SingleAsync()).UpdatedDate;
        command.ExpectedTrialUpdatedDate = (await db.SampleRequestSampleTrials.SingleAsync(t => t.TrialNo == 3)).UpdatedDate;
        command.CorrectionReason = "Customer also accepted this option";
        var changed = await handler.Handle(command, default); Assert.False(changed.Success);
        db.ChangeTracker.Clear(); Assert.Equal(trials[0].FormulaId, (await db.SampleRequests.SingleAsync()).FormulaId);
        Assert.Equal(1, await db.SampleRequestSampleTrials.CountAsync(t => t.CustomerReplyStatus == "APPROVED"));
        parent = await db.SampleRequests.SingleAsync(); parent.ManagerBy = Guid.NewGuid(); await db.SaveChangesAsync(); db.ChangeTracker.Clear();
        command.OperationId = Guid.NewGuid(); Assert.False((await handler.Handle(command, default)).Success);
        parent = await db.SampleRequests.SingleAsync(); parent.ManagerBy = employee; parent.CompanyId = Guid.NewGuid(); await db.SaveChangesAsync(); db.ChangeTracker.Clear();
        Assert.Null(await new GetSampleDeliveriesQueryHandler(db, user, permissions, visibility).Handle(new(parent.SampleRequestId), default));
        Assert.False((await handler.Handle(command, default)).Success);
    }
    private sealed class Clock : IDateTimeProvider { public DateTime Now => new(2026,11,16,10,0,0); }
    internal static async Task CreateTable(NpgsqlConnection connection, IEntityType entity)
    {
        var table = StoreObjectIdentifier.Table(entity.GetTableName()!, entity.GetSchema());
        var columns = entity.GetProperties().Select(p =>
        {
            var defaultSql = p.TryGetDefaultValue(out var value) && value is not null
                ? " DEFAULT " + p.GetRelationalTypeMapping().GenerateSqlLiteral(value) : "";
            return $"\"{p.GetColumnName(table)}\" {p.GetRelationalTypeMapping().StoreType} NULL{defaultSql}";
        });
        var key = entity.FindPrimaryKey()!.Properties.Single().GetColumnName(table);
        // Chỉ metadata EF tin cậy trên cluster test loopback đã kiểm tra data_directory.
        await using var command = new NpgsqlCommand($"CREATE SCHEMA IF NOT EXISTS \"{table.Schema}\"; CREATE TABLE \"{table.Schema}\".\"{table.Name}\" ({string.Join(',', columns)}, PRIMARY KEY (\"{key}\"));", connection);
        await command.ExecuteNonQueryAsync();
    }
}
